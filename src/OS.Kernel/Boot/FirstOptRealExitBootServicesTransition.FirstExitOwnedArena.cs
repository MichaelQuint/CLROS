/// <summary>
/// Materialize retained data in one caller-owned writable EFI allocation.
/// Page 0 holds contexts; pages 1..4 hold GDT/TSS/final IDT/bridge IDT; 5..20
/// hold the map; 22..85 hold the main stack; 88..91,94..97,100..103 hold ISTs.
/// The remaining eight pages are guard reservations: this helper does not unmap
/// them. The eventual owned hierarchy must omit them and map all other pages RW,
/// NX. Firmware mappings remain unchanged while preparing/calling boot services.
/// The separate vector page is reserved by address during preparation and must
/// contain authenticated owned terminal stubs before entry. Retain the original
/// state exclusively; never copy/reset it or free its
/// storage after successful EBS. Preparation does not load any CPU descriptor.
/// </summary>

public static unsafe class FirstExitOwnedArena
{
    public const uint PageCount = 105;
    public const uint Bytes = PageCount * 4096;
    public const uint MapBytes = 16 * 4096;
    public const uint MappingRangeCount = 5;
    public const ulong LowerCanary = 0x4d3033535441434b;
    public const ulong UpperCanary = 0x4d30335550504552;
    private const ulong LowEnd = 0x0000800000000000;
    public static bool IsGuardPage(uint page) => page == 21 || page == 86 || page == 87 || page == 92 || page == 93 || page == 98 || page == 99 || page == 104;
    /// <summary>
    /// Describe only the retained arena's non-guard pages for BuildRetainedImage.
    /// Other retained image/allocator/ACPI/code ranges remain caller obligations.
    /// This writes declarations, not page tables; it does not change live mappings.
    /// Keep the original ready state and accessible arena stable during this call.
    /// </summary>

    public static bool WriteMappingRanges(ref FirstExitOwnedArenaState state, SeparatePageFaultMappingRange* ranges, ulong capacity, out ulong written)
    {
        written = 0;
        ulong bytes = MappingRangeCount * (ulong)sizeof(SeparatePageFaultMappingRange);
        if (!state.IsReady || !PageRange((ulong)state.Data, Bytes) || ranges == null || ((ulong)ranges & 7) != 0 || (ulong)ranges >= LowEnd - bytes || capacity < MappingRangeCount || capacity > SeparateDisabledDefaultPageFaultPageTables.MaximumRetainedRanges || (FirstExitDescriptors.Overlaps((ulong)ranges, bytes, (ulong)state.Data, Bytes) && !InMainStack(state, (ulong)ranges, bytes)))
            return false;
        fixed (FirstExitOwnedArenaState* address = &state)
            if (FirstExitDescriptors.Overlaps((ulong)ranges, bytes, (ulong)address, (ulong)sizeof(FirstExitOwnedArenaState)))
                return false;
        if (!ValidateCanaries(state))
            return false;
        // The shared guard predicate is the single source of interval boundaries.
        uint start = 0;
        for (uint page = 0; page <= PageCount; page++)
        {
            if (page != PageCount && !IsGuardPage(page))
                continue;
            if (page > start)
                ranges[written++] = new SeparatePageFaultMappingRange((ulong)state.Data + start * 4096UL, page - start, PageProtection.Read | PageProtection.Write);
            start = page + 1;
        }

        return written == MappingRangeCount;
    }

    public static bool Materialize(ref FirstExitOwnedArenaState state, byte* data, ulong capacity, ulong ownedVectorPage, ushort firmwareCs)
    {
        if (state.Phase != 0 || capacity != Bytes || !PageRange((ulong)data, capacity) || !PageRange(ownedVectorPage, 4096) || FirstExitDescriptors.Overlaps((ulong)data, capacity, ownedVectorPage, 4096) || (firmwareCs & 7) != 0 || (firmwareCs != 8 && firmwareCs < 40) || firmwareCs > 4088 || sizeof(FirstExitDescriptorContext) > 128 || sizeof(FirstExitOwnedStackContext) > 128 || sizeof(FirstExitPermanentCr3Context) > 128 || sizeof(FirstExitFirmwareBindingState) > 128 || sizeof(FirstExitTransitionState) > 512 || sizeof(FirstExitFaultContext) > 4096 - 1024)
            return false;
        fixed (FirstExitOwnedArenaState* address = &state)
        {
            ulong start = (ulong)address, bytes = (ulong)sizeof(FirstExitOwnedArenaState);
            if (start == 0 || start >= LowEnd - bytes || (start & 7) != 0 || FirstExitDescriptors.Overlaps(start, bytes, (ulong)data, capacity) || FirstExitDescriptors.Overlaps(start, bytes, ownedVectorPage, 4096))
                return false;
        }

        // Admission is complete. A later encoding/readback failure consumes the
        // state and retains Storage for pre-EBS cleanup; no ready view escapes.
        state.Data = data;
        state.Phase = 1;
        for (uint i = 0; i < Bytes; i++)
            data[i] = 0;
        byte* gdt = data + 4096, tss = data + 8192, idt = data + 12288, bridge = data + 16384;
        *(ulong*)(tss + 4) = (ulong)data + 86 * 4096 - 16;
        *(ushort*)(tss + 102) = 104;
        WriteCanaries(data, 22, 86);
        for (uint stack = 0; stack < 3; stack++)
        {
            uint first = 88 + stack * 6, end = first + 4;
            *(ulong*)(tss + 36 + stack * 8) = (ulong)data + end * 4096 - 16;
            WriteCanaries(data, first, end);
        }

        bool prepared = OS.Kernel.Diagnostics.OwnedX64GdtContainingNullN64BitCode.Encode(gdt, 4096, (ulong)tss, 103).Succeeded && OS.Kernel.Diagnostics.PopulateAllN256IDTVectorsOwnedGatesNever.Materialize(idt, 4096, (ulong)idt, ownedVectorPage).Succeeded && FirstExitDescriptors.Prepare(ref *(FirstExitDescriptorContext*)data, gdt, 4096, tss, 104, idt, 4096, bridge, 4096, firmwareCs);
        state.Phase = prepared ? 2u : 3u;
        if (!prepared)
            return false;
        if (ValidateCanaries(state))
            return true;
        state.Phase = 3;
        return false;
    }

    public static bool ValidateCanaries(FirstExitOwnedArenaState state)
    {
        if (!state.IsReady || !PageRange((ulong)state.Data, Bytes))
            return false;
        if (!CanariesMatch(state.Data, 22, 86))
            return false;
        for (uint stack = 0; stack < 3; stack++)
            if (!CanariesMatch(state.Data, 88 + stack * 6, 92 + stack * 6))
                return false;
        return true;
    }

    /// <summary>
    /// Read back the original, not-yet-installed descriptor storage against the
    /// exact reserved vector page and owned stack locations. Refuse changed
    /// pointers before following them. This does not observe live GDTR/IDTR/TR.
    /// </summary>

    public static bool ValidateDescriptors(ref FirstExitOwnedArenaState state, ulong vectorPage) => ValidateDescriptorsCore(ref state, vectorPage, false, state.StackTop, 0);
    // Validate supplied installed storage and native-recorded observations. This
    // helper itself does not execute SGDT/SIDT/STR or establish their provenance.
    public static bool ValidateInstalledDescriptors(ref FirstExitOwnedArenaState state, ulong vectorPage) => ValidateDescriptorsCore(ref state, vectorPage, true, state.StackTop, 0);
    /// <summary>Nonmutating installed-storage check with exact owner-declared
    /// TSS.RSP0 and IST4 stack tops; zero IST4 means unborrowed. The IRQ-off owner
    /// must authenticate the borrow and retain mapped stacks until restoration.
    /// Every other descriptor byte and recorded adoption observation stays
    /// original. Invalid tops or any mismatch fail closed. This does not observe
    /// live GDTR/IDTR/TR, authorize a borrow or certify stack mappings.</summary>

    public static bool ValidateInstalledDescriptors(ref FirstExitOwnedArenaState state, ulong vectorPage, ulong expectedRsp0, ulong expectedIst4) => ValidateDescriptorsCore(ref state, vectorPage, true, expectedRsp0, expectedIst4);
    private static bool ValidateDescriptorsCore(ref FirstExitOwnedArenaState state, ulong vectorPage, bool installed, ulong expectedRsp0, ulong expectedIst4)
    {
        if (expectedRsp0 < 4096 || expectedRsp0 >= LowEnd || (expectedRsp0 & 15) != 0 || (expectedIst4 != 0 && (expectedIst4 < 4096 || expectedIst4 >= LowEnd || (expectedIst4 & 15) != 0)) || state.Reserved != 0 || !PageRange(vectorPage, 4096) || !ValidateCanaries(state) || FirstExitDescriptors.Overlaps((ulong)state.Data, Bytes, vectorPage, 4096))
            return false;
        FirstExitDescriptorContext* context = state.Descriptors;
        byte* gdt = state.Data + 4096, tss = state.Data + 8192;
        byte* finalIdt = state.Data + 12288, bridge = state.Data + 16384;
        ushort cs = context->FirmwareCs;
        // The native adoption stub consumes the descriptor context before LIDT/LGDT/LTR.
        if (context->Prepared != (installed ? 2u : 1u) || (cs & 7) != 0 || (cs != 8 && cs < 40) || cs > 4088 || context->Gdt != gdt || context->Tss != tss || context->FinalIdt != finalIdt || context->BridgeIdt != bridge || !PseudoDescriptor(context->Gdtr, gdt, (ushort)(cs < 40 ? 39 : cs + 7)) || !PseudoDescriptor(context->FinalIdtr, finalIdt, 4095) || !PseudoDescriptor(context->BridgeIdtr, bridge, 4095) || context->ObservedTr != (installed ? 24 : 0) || context->ObservedCs != (installed ? 8 : 0) || context->ObservedDs != (installed ? 16 : 0) || context->ObservedEs != (installed ? 16 : 0) || context->ObservedSs != (installed ? 16 : 0) || !PopulateAllN256IDTVectorsOwnedGatesNever.ValidateReadBack(finalIdt, 4096, (ulong)finalIdt, vectorPage).Succeeded)
            return false;
        byte* expectedGdt = stackalloc byte[40];
        if (!OwnedX64GdtContainingNullN64BitCode.Encode(expectedGdt, 40, (ulong)tss, 103).Succeeded)
            return false;
        if (installed)
            expectedGdt[29] |= 2; // LTR must have made this TSS busy.
        for (int i = 0; i < 40; i++)
        {
            byte observed = gdt[i];
            if (installed && (i == 13 || i == 21))
                observed &= 0xfe; // hardware accessed bit only
            if (observed != expectedGdt[i])
                return false;
        }

        for (int i = 0; i < 16; i++)
            if (context->ObservedGdtr[i] != (installed ? context->Gdtr[i] : 0) || context->ObservedIdtr[i] != (installed ? context->FinalIdtr[i] : 0))
                return false;
        for (int i = 40; i < 4096; i++)
        {
            byte expected = cs >= 40 && i >= cs && i - cs < 8 ? expectedGdt[8 + i - cs] : (byte)0;
            byte observed = gdt[i];
            if (installed && cs >= 40 && i == cs + 5)
                observed &= 0xfe;
            if (observed != expected)
                return false;
        }

        for (int i = 0; i < 4096; i++)
        {
            byte expected = 0;
            if (i >= 4 && i < 12)
                expected = (byte)(expectedRsp0 >> ((i - 4) * 8));
            else if (i >= 36 && i < 60)
            {
                int stack = (i - 36) / 8;
                ulong top = (ulong)state.Data + (ulong)(92 + stack * 6) * 4096 - 16;
                expected = (byte)(top >> (((i - 36) % 8) * 8));
            }
            else if (i >= 60 && i < 68)
                expected = (byte)(expectedIst4 >> ((i - 60) * 8));
            else if (i == 102)
                expected = 104;
            if (tss[i] != expected)
                return false;
            int gateOffset = i & 15;
            expected = gateOffset == 2 ? (byte)cs : gateOffset == 3 ? (byte)(cs >> 8) : gateOffset == 4 ? (byte)0 : finalIdt[i];
            if (bridge[i] != expected)
                return false;
        }

        return true;
    }

    private static bool PseudoDescriptor(byte* descriptor, byte* table, ushort limit)
    {
        if (*(ushort*)descriptor != limit || *(ulong*)(descriptor + 2) != (ulong)table)
            return false;
        for (int i = 10; i < 16; i++)
            if (descriptor[i] != 0)
                return false;
        return true;
    }

    internal static bool InMainStack(FirstExitOwnedArenaState state, ulong address, ulong bytes) => state.IsReady && PageRange((ulong)state.Data, Bytes) && bytes != 0 && address >= state.StackBottom && address < state.StackTop && bytes <= state.StackTop - address;
    private static bool PageRange(ulong start, ulong bytes) => start != 0 && start < LowEnd && (start & 4095) == 0 && bytes < LowEnd - start;
    private static void WriteCanaries(byte* data, uint firstPage, uint endPage)
    {
        *(ulong*)(data + firstPage * 4096) = LowerCanary;
        *(ulong*)(data + endPage * 4096 - 16) = UpperCanary;
    }

    private static bool CanariesMatch(byte* data, uint firstPage, uint endPage) => *(ulong*)(data + firstPage * 4096) == LowerCanary && *(ulong*)(data + endPage * 4096 - 16) == UpperCanary;
}
