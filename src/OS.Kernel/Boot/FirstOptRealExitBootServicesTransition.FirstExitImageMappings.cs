/// <summary>
/// Derive retained identity ranges from the original loaded x64 EFI PE image.
/// Capture/mapping provenance and readable, stable backing remain caller obligations;
/// this validates supplied PE structure, not the loader or actual CPU permissions.
/// Keep headers RO/NX, code RX and writable data RW/NX, including static allocator
/// metadata and copied ACPI buffers within those data sections. Gaps remain absent.
/// Separate runtime allocations still require their own retained ranges.
/// </summary>

public static unsafe class FirstExitImageMappings
{
    public const ulong MaximumSections = 16;
    private const ulong Page = 4096;
    private const ulong LowEnd = 0x0000800000000000;
    private const uint Read = 0x40000000, Write = 0x80000000, Execute = 0x20000000;
    public static bool WriteRanges(EfiLoadedImageRangeCapturePlan capture, M01LoadedImageVirtualMappingEvidence mapping, SeparatePageFaultMappingRange* ranges, ulong capacity, out ulong written)
    {
        written = 0;
        ulong bytes = capture.Range.ImageSize;
        if (sizeof(void*) != 8 || !capture.Succeeded || !mapping.IsValidFor(capture) || mapping.VirtualImageBase.TryGetRawValueForUefiBoundary(out ulong address) != AddressValueStatus.Success || address < Page || (address & (Page - 1)) != 0 || bytes < Page || bytes > SeparateDisabledDefaultPageFaultPageTables.MaximumRetainedMappedPages * Page || (bytes & (Page - 1)) != 0 || address >= LowEnd - bytes)
            return false;
        byte* image = (byte*)address;
        if (*(ushort*)image != 0x5a4d)
            return false;
        ulong nt = *(uint*)(image + 60);
        if (nt < 64 || nt > bytes - 24)
            return false;
        byte* pe = image + nt;
        ulong optionalBytes = *(ushort*)(pe + 20), sections = *(ushort*)(pe + 6);
        if (*(uint*)pe != 0x00004550 || *(ushort*)(pe + 4) != 0x8664 || (*(ushort*)(pe + 22) & 2) == 0 || sections == 0 || sections > MaximumSections || optionalBytes < 112 || optionalBytes > bytes - nt - 24)
            return false;
        byte* optional = pe + 24;
        ulong directories = *(uint*)(optional + 108), fileAlignment = *(uint*)(optional + 36);
        if (*(ushort*)optional != 0x20b || *(uint*)(optional + 32) != Page || *(uint*)(optional + 56) != bytes || *(ushort*)(optional + 68) != 10 || fileAlignment < 512 || fileAlignment > Page || (fileAlignment & (fileAlignment - 1)) != 0 || directories > 16 || 112 + directories * 8 > optionalBytes)
            return false;
        ulong table = nt + 24 + optionalBytes, headers = *(uint*)(optional + 60);
        if (table > bytes || sections * 40 > bytes - table || headers < table + sections * 40 || headers > bytes || (headers & (fileAlignment - 1)) != 0)
            return false;
        ulong headerPages = (headers + Page - 1) / Page;
        if (headerPages > SeparateDisabledDefaultPageFaultPageTables.MaximumRetainedRangePages)
            return false;
        ulong priorEnd = headerPages * Page, mappedPages = headerPages;
        ulong entry = *(uint*)(optional + 16);
        bool entryCovered = false;
        for (ulong index = 0; index < sections; index++)
        {
            byte* section = image + table + index * 40;
            ulong virtualBytes = *(uint*)(section + 8), start = *(uint*)(section + 12);
            ulong rawBytes = *(uint*)(section + 16);
            uint flags = *(uint*)(section + 36);
            ulong extent = virtualBytes > rawBytes ? virtualBytes : rawBytes;
            if (virtualBytes == 0 || (rawBytes & (fileAlignment - 1)) != 0 || (start & (Page - 1)) != 0 || start < priorEnd || start > bytes || extent > bytes - start || (flags & Read) == 0 || (flags & (Write | Execute)) == (Write | Execute) || (flags & 0x04000000) != 0)
                return false; // no noncached section policy
            ulong pages = (extent + Page - 1) / Page;
            if (pages > SeparateDisabledDefaultPageFaultPageTables.MaximumRetainedRangePages || pages * Page > bytes - start)
                return false;
            priorEnd = start + pages * Page;
            mappedPages += pages;
            if ((flags & Execute) != 0 && entry >= start && entry - start < virtualBytes)
                entryCovered = true;
        }

        if (!entryCovered || mappedPages > SeparateDisabledDefaultPageFaultPageTables.MaximumRetainedMappedPages || ranges == null || ((ulong)ranges & 7) != 0 || capacity < sections + 1 || capacity > SeparateDisabledDefaultPageFaultPageTables.MaximumRetainedRanges)
            return false;
        ulong outputBytes = (sections + 1) * (ulong)sizeof(SeparatePageFaultMappingRange);
        if ((ulong)ranges >= LowEnd - outputBytes || FirstExitDescriptors.Overlaps((ulong)ranges, outputBytes, address, bytes))
            return false;
        // All admission checks precede output writes. The original image must
        // remain stable for both passes; this method does not grant lifetime authority.
        ranges[0] = new SeparatePageFaultMappingRange(address, headerPages, PageProtection.Read);
        for (ulong index = 0; index < sections; index++)
        {
            byte* section = image + table + index * 40;
            ulong extent = *(uint*)(section + 8), rawBytes = *(uint*)(section + 16);
            if (rawBytes > extent)
                extent = rawBytes;
            uint flags = *(uint*)(section + 36);
            PageProtection protection = PageProtection.Read;
            if ((flags & Write) != 0)
                protection |= PageProtection.Write;
            if ((flags & Execute) != 0)
                protection |= PageProtection.Execute;
            ranges[index + 1] = new SeparatePageFaultMappingRange(address + *(uint*)(section + 12), (extent + Page - 1) / Page, protection);
        }

        written = sections + 1;
        return true;
    }

    /// <summary>
    /// Check a required object/function interval against a previously validated,
    /// stable range list. Numeric containment is not allocation or execution authority.
    /// </summary>

    public static bool Contains(SeparatePageFaultMappingRange* ranges, ulong count, ulong address, ulong bytes, PageProtection protection)
    {
        if (ranges == null || ((ulong)ranges & 7) != 0 || count == 0 || count > SeparateDisabledDefaultPageFaultPageTables.MaximumRetainedRanges || (ulong)ranges >= LowEnd - count * (ulong)sizeof(SeparatePageFaultMappingRange) || address == 0 || bytes == 0 || bytes >= LowEnd || address >= LowEnd - bytes)
            return false;
        for (ulong index = 0; index < count; index++)
        {
            SeparatePageFaultMappingRange range = ranges[index];
            if (!range.IsInitialized || range.PageCount == 0 || range.PageCount > SeparateDisabledDefaultPageFaultPageTables.MaximumRetainedRangePages)
                return false;
            ulong length = range.PageCount * Page;
            if (range.Protection == protection && address >= range.Start && address - range.Start < length && bytes <= length - (address - range.Start))
                return true;
        }

        return false;
    }
}
