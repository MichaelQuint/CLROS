        [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
        internal static byte ReadByte(byte* address) => *address;

        internal static bool Guards(Buffer* b) =>
            b->Before0 == Guard0 && b->Before1 == Guard1 &&
            b->After0 == Guard1 && b->After1 == Guard0;
        internal static bool Zero(byte* bytes, int start, int count)
        {
            for (int i = start; i < start + count; i++) if (ReadByte(bytes + i) != 0) return false;
            return true;
