    // One pre-EBS acquisition. The host Span/interface contract is deliberately
    // separate; this EFI boundary has only numeric values and admitted pointers.
    internal static partial class FirmwareEntropyCapture
    {
        internal const ulong RequestedBytes = 32;
        internal const ulong PayloadBytes = 64;
        internal const ulong NotFound = 0x800000000000000EUL;
        private const ulong Guard0 = 0x39D18A675BE024CFUL;
        private const ulong Guard1 = 0xE62740BC951ADF38UL;























        private static State s_state;
        private static Buffer s_scratch, s_retained;

        private static bool Span(ulong start, ulong length, ulong alignment) =>
            start != 0 && (start & (alignment - 1)) == 0 &&
            length != 0 && start <= ulong.MaxValue - length;
        private static bool Apart(ulong a, ulong an, ulong b, ulong bn) =>
            a + an <= b || b + bn <= a;
        private static bool Excluded(ulong p, ulong n, State* s, Buffer* scratch, Buffer* retained) =>
            Apart(p, n, (ulong)s, (ulong)sizeof(State)) &&
            Apart(p, n, (ulong)scratch, (ulong)sizeof(Buffer)) &&
            Apart(p, n, (ulong)retained, (ulong)sizeof(Buffer));

        // The firmware-owned tables must be genuine caller-provided readable
        // storage. Numeric admission rejects malformed extents; it is not a
        // mapping oracle for arbitrary addresses supplied by an attacker.
        internal static bool Begin(State* s, Buffer* scratch, Buffer* retained, EfiSystemTable* table)
        {
            if (!Span((ulong)s, (ulong)sizeof(State), 8) ||
                !Span((ulong)scratch, (ulong)sizeof(Buffer), 8) ||
                !Span((ulong)retained, (ulong)sizeof(Buffer), 8) ||
                !Span((ulong)table, (ulong)sizeof(EfiSystemTable), 8) ||
                !Apart((ulong)s, (ulong)sizeof(State), (ulong)scratch, (ulong)sizeof(Buffer)) ||
                !Apart((ulong)s, (ulong)sizeof(State), (ulong)retained, (ulong)sizeof(Buffer)) ||
                !Apart((ulong)scratch, (ulong)sizeof(Buffer), (ulong)retained, (ulong)sizeof(Buffer)) ||
                !Excluded((ulong)table, (ulong)sizeof(EfiSystemTable), s, scratch, retained)) return false;
            EfiBootServices* services = table->BootServices;
            if (!Span((ulong)services, (ulong)sizeof(EfiBootServices), 8) ||
                !Excluded((ulong)services, (ulong)sizeof(EfiBootServices), s, scratch, retained) ||
                !Apart((ulong)table, (ulong)sizeof(EfiSystemTable), (ulong)services, (ulong)sizeof(EfiBootServices))) return false;
            delegate* unmanaged<EfiGuid*, void*, void**, ulong> locate = services->LocateProtocol;
            if (!Span((ulong)locate, 1, 1) || !Excluded((ulong)locate, 1, s, scratch, retained) ||
                !Apart((ulong)locate, 1, (ulong)table, (ulong)sizeof(EfiSystemTable)) ||
                !Apart((ulong)locate, 1, (ulong)services, (ulong)sizeof(EfiBootServices))) return false;
            for (int i = 0; i < sizeof(State); i++) if (((byte*)s)[i] != 0) return false;
            for (int i = 0; i < 64; i++)
                if (ReadByte(scratch->Data + i) != 0 || ReadByte(retained->Data + i) != 0) return false;
            // No rejected admission above changes state, guards or payloads.
            scratch->Before0 = retained->Before0 = Guard0;
            scratch->Before1 = retained->Before1 = Guard1;
            scratch->After0 = retained->After0 = Guard1;
            scratch->After1 = retained->After1 = Guard0;
            s->SystemTable = table; s->BootServices = services; s->Locate = locate;
            s->Scratch = scratch; s->Retained = retained; s->Phase = 1;
            return true;
