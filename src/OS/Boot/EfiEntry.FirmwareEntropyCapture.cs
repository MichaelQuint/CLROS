        private static bool Fail(State* s, ulong error)
        { s->Error = error; s->Phase = 4; return false; }

        internal static bool Acquire(State* s)
        {
            if (s->Phase != 1 || s->LocateCalls != 0 || s->RngCalls != 0 || s->PublishedBytes != 0) return false;
            EfiGuid guid;
            guid.Data1 = 0x3152BCA5; guid.Data2 = 0xEADE; guid.Data3 = 0x433D;
            guid.Data4_0 = 0x86; guid.Data4_1 = 0x2E; guid.Data4_2 = 0xC0; guid.Data4_3 = 0x1C;
            guid.Data4_4 = 0xDC; guid.Data4_5 = 0x29; guid.Data4_6 = 0x1F; guid.Data4_7 = 0x44;
            s->Phase = 2; s->LocateCalls = 1;
            s->LocateStatus = s->Locate(&guid, null, (void**)&s->Rng);
            if (s->LocateStatus != 0)
            {
                if (!FailureStorageIntact(s)) return Fail(s, 6);
                return Fail(s, s->LocateStatus == NotFound ? 2UL : 3UL);
            }
            Protocol* rng = s->Rng;
            if (!Span((ulong)rng, (ulong)sizeof(Protocol), 8) ||
                !Excluded((ulong)rng, (ulong)sizeof(Protocol), s, s->Scratch, s->Retained) ||
                !Apart((ulong)rng, (ulong)sizeof(Protocol), (ulong)s->SystemTable, (ulong)sizeof(EfiSystemTable)) ||
                !Apart((ulong)rng, (ulong)sizeof(Protocol), (ulong)s->BootServices, (ulong)sizeof(EfiBootServices)) ||
                !Apart((ulong)rng, (ulong)sizeof(Protocol), (ulong)&guid, (ulong)sizeof(EfiGuid))) return Fail(s, 4);
            delegate* unmanaged<Protocol*, EfiGuid*, nuint, byte*, ulong> get = rng->GetRng;
            if (!Span((ulong)get, 1, 1) || !Excluded((ulong)get, 1, s, s->Scratch, s->Retained) ||
                !Apart((ulong)get, 1, (ulong)rng, (ulong)sizeof(Protocol)) ||
                !Apart((ulong)get, 1, (ulong)s->SystemTable, (ulong)sizeof(EfiSystemTable)) ||
                !Apart((ulong)get, 1, (ulong)s->BootServices, (ulong)sizeof(EfiBootServices))) return Fail(s, 4);
            s->GetRng = get; s->RngCalls = 1;
            s->RngStatus = get(rng, null, (nuint)RequestedBytes, s->Scratch->Data);
            if (s->RngStatus != 0)
            {
                if (!FailureStorageIntact(s)) return Fail(s, 6);
                return Fail(s, 5);
            }
            return Retain(s);
        }

        private static bool FailureStorageIntact(State* s) =>
            Guards(s->Scratch) && Guards(s->Retained) &&
            Zero(s->Scratch->Data, 32, 32) && Zero(s->Retained->Data, 0, 64);

        internal static bool Retain(State* s)
        {
            if (s->Phase != 2 || s->LocateCalls != 1 || s->LocateStatus != 0 ||
                s->RngCalls != 1 || s->RngStatus != 0 || s->PublishedBytes != 0) return false;
            Buffer* scratch = s->Scratch; Buffer* retained = s->Retained;
            if (!Guards(scratch) || !Guards(retained) || !Zero(scratch->Data, 32, 32) ||
                !Zero(retained->Data, 0, 64)) return Fail(s, 6);
            for (int i = 0; i < 32; i++)
            {
                byte value = ReadByte(scratch->Data + i);
                retained->Data[i] = value;
                if (ReadByte(retained->Data + i) != value) return Fail(s, 7);
                scratch->Data[i] = 0;
                if (ReadByte(scratch->Data + i) != 0 || ReadByte(retained->Data + i) != value) return Fail(s, 7);
            }
            if (!Zero(scratch->Data, 0, 64) || !Zero(retained->Data, 32, 32) ||
                !Guards(scratch) || !Guards(retained)) return Fail(s, 7);
            s->PublishedBytes = RequestedBytes; s->Phase = 3;
            return true;
        }

        // Public completion state only; never classify failure scratch bytes for output.
        internal static ulong ClearedBytes(State* s) =>
            s->Phase == 3 && s->PublishedBytes == RequestedBytes ? RequestedBytes : 0;

        internal static bool Run(EfiSystemTable* table, EfiSimpleTextOutputProtocol* console, EfiSerialIoProtocol* serial)
        {
            Token(console, serial, 0);
            fixed (State* s = &s_state)
            fixed (Buffer* scratch = &s_scratch)
            fixed (Buffer* retained = &s_retained)
            {
                if (!Begin(s, scratch, retained, table)) { Token(console, serial, 1); return false; }
                bool success = Acquire(s);
                Token(console, serial, 2); WriteUnsignedDecimal(console, serial, s->LocateStatus);
                Token(console, serial, 3); WriteUnsignedDecimal(console, serial, s->LocateCalls);
                Token(console, serial, 4); WriteUnsignedDecimal(console, serial, s->LocateStatus == 0 && s->Rng != null ? 1UL : 0UL);
                WriteCrLf(console, serial);
                Token(console, serial, 5); WriteUnsignedDecimal(console, serial, s->RngStatus);
                Token(console, serial, 3); WriteUnsignedDecimal(console, serial, s->RngCalls);
                Token(console, serial, 6);
                Token(console, serial, 7); WriteUnsignedDecimal(console, serial, s->PublishedBytes);
                Token(console, serial, 8); WriteUnsignedDecimal(console, serial, ClearedBytes(s));
                Token(console, serial, 9); WriteUnsignedDecimal(console, serial, Guards(scratch) && Guards(retained) ? 64UL : 0UL);
                Token(console, serial, 10); WriteUnsignedDecimal(console, serial, Zero(scratch->Data, 32, 32) && Zero(retained->Data, 32, 32) ? 64UL : 0UL);
                Token(console, serial, 11); WriteUnsignedDecimal(console, serial, s->Phase == 3 ? 1UL : 0UL);
                WriteCrLf(console, serial);
                if (success) { Token(console, serial, 12); return true; }
                if (s->Error == 2) Token(console, serial, 18);
                Token(console, serial, s->Error == 2 ? 13 : s->Error == 3 ? 14 : s->Error == 4 ? 15 : s->Error == 5 ? 16 : 17);
                return false;
            }
        }
