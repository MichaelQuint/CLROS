    // Private fixed-page diagnostic adapter. All authority stays in the original
    // M01 storage; snapshots below are observations, never replacement allocators.
    private static class M04ManagedHeapAdapter
    {
        private static bool s_reservationObserved;

        public static bool Checkpoint(bool initialize, M01LiveAllocatorStaticState* state,
            BootMemoryRegionRecord* record, BootReservedRange* ledger,
            ManagedHeapPageRangeState* heap, EfiSimpleTextOutputProtocol* console,
            EfiSerialIoProtocol* serial)
        {
            if (initialize) Token(console, serial, 0);
            if (state == null || record == null || ledger == null || heap == null ||
                (initialize && !state->IsCompleted))
                return Fail(console, serial, heap, 1);
            ulong index = 5;
            for (ulong i = 0; i < 5; i++)
            {
                if (ledger[i].Kind == BootReservationKind.AllocatorArena)
                {
                    if (index != 5) return Fail(console, serial, heap, 2);
                    index = i;
                }
            }
            if (index == 5 || !ledger[index].Equals(state->ArenaReservation) ||
                !ledger[index].IsValid || ledger[index].PageCount != 2 ||
                ledger[index].ByteLength != 8192 ||
                ledger[index].PhysicalStart.TryGetRawValueForUefiBoundary(out ulong start) != AddressValueStatus.Success ||
                ledger[index].PhysicalEndExclusive.TryGetRawValueForUefiBoundary(out ulong end) != AddressValueStatus.Success ||
                start == 0 || start > ~0UL - 8192 || end != start + 8192 ||
                record->UefiType != 2 || record->PhysicalStart != start ||
                record->PhysicalEndExclusive != end || record->PageCount != 2 ||
                record->ByteLength != 8192 || record->VirtualStart != start || record->Attribute != 0)
                return Fail(console, serial, heap, 3);

            BootPageAllocatorState* allocator = &state->AllocatorStateValue;
            BootPageFreeListNode* nodes = &state->FreeNodeValue;
            BootPageAllocatorState before = *allocator;
            ManagedHeapPageRangeResult result;
            if (initialize)
                result = ManagedHeapPageRangeLiveAllocator.ReserveAndInitializeOnce(
                    allocator, 1, nodes, 1, 1, ledger, 5, 5, index,
                    (byte*)start, 8192, heap, ManagedHeapPageRangeLiveAllocator.RequiredStateBytes);
            else
                result = ManagedHeapPageRangeLiveAllocator.ValidateRetained(
                    allocator, 1, nodes, 1, 1, ledger, 5, 5, index,
                    (byte*)start, 8192, heap, ManagedHeapPageRangeLiveAllocator.RequiredStateBytes);
            if (heap->Lifecycle == ManagedHeapPageRangeLifecycle.ReservedNotReady ||
                heap->Lifecycle == ManagedHeapPageRangeLifecycle.Ready)
                s_reservationObserved = true;
            BootPageAllocatorState current = *allocator;
            if (!result.IsReady || result.ReadBytes != 4096 || !result.ContentsAreZeroNow ||
                heap->Lifecycle != ManagedHeapPageRangeLifecycle.Ready ||
                heap->SelfAddress != (ulong)heap || heap->AllocatorAddress != (ulong)allocator ||
                heap->NodesAddress != (ulong)nodes || heap->LedgerAddress != (ulong)ledger ||
                heap->ParentIndex != index || heap->BackingAddress != start ||
                !heap->Parent.Equals(ledger[index]) || heap->PhysicalStart != start ||
                heap->PhysicalEndExclusive != start + 4096 ||
                result.PhysicalStart != heap->PhysicalStart ||
                result.PhysicalEndExclusive != heap->PhysicalEndExclusive || result.MappedStart != start ||
                !Same(result.InitialAllocatorState, heap->InitialAllocatorState) ||
                !Same(result.CurrentAllocatorState, current) ||
                !Accounting(result.InitialAllocatorState, 2, 0) || !Accounting(current, 1, 1) ||
                (initialize && !Same(before, result.InitialAllocatorState)))
                return Fail(console, serial, heap, 4);

            // Result endpoints were checked before subtraction. No invented size fields.
            ulong bytes = result.PhysicalEndExclusive - result.PhysicalStart;
            ulong pages = bytes / 4096;
            if (bytes != 4096 || pages != 1) return Fail(console, serial, heap, 5);
            Token(console, serial, initialize ? 1 : 2);
            Hex(console, serial, (ulong)allocator);
            Token(console, serial, 3); Hex(console, serial, (ulong)nodes);
            Token(console, serial, 4); Hex(console, serial, (ulong)heap);
            Token(console, serial, 5); Hex(console, serial, (ulong)ledger);
            Token(console, serial, 6); WriteUnsignedDecimal(console, serial, index);
            Token(console, serial, 7); Hex(console, serial, start);
            Token(console, serial, 8); Hex(console, serial, end);
            Token(console, serial, 9); Hex(console, serial, (ulong)(byte*)start);
            Token(console, serial, 10); Hex(console, serial, result.PhysicalStart);
            Token(console, serial, 11); Hex(console, serial, result.PhysicalEndExclusive);
            Token(console, serial, 12);
            if (initialize)
            {
                Token(console, serial, 13); WriteUnsignedDecimal(console, serial, pages);
                Token(console, serial, 14); WriteUnsignedDecimal(console, serial, bytes);
                Token(console, serial, 15); WriteUnsignedDecimal(console, serial, before.FreePageCount);
                Token(console, serial, 16); WriteUnsignedDecimal(console, serial, before.FreeByteCount);
                Token(console, serial, 17); WriteUnsignedDecimal(console, serial, before.AllocatedPageCount);
                Token(console, serial, 18); WriteUnsignedDecimal(console, serial, before.AllocatedByteCount);
            }
            Token(console, serial, initialize ? 19 : 23); WriteUnsignedDecimal(console, serial, current.FreePageCount);
            Token(console, serial, initialize ? 20 : 24); WriteUnsignedDecimal(console, serial, current.FreeByteCount);
            Token(console, serial, initialize ? 21 : 25); WriteUnsignedDecimal(console, serial, current.AllocatedPageCount);
            Token(console, serial, initialize ? 22 : 26); WriteUnsignedDecimal(console, serial, current.AllocatedByteCount);
            Token(console, serial, 27); WriteUnsignedDecimal(console, serial, result.ReadBytes);
            Token(console, serial, 28); Token(console, serial, result.ContentsAreZeroNow ? 29 : 30);
            Token(console, serial, 12);
            if (!initialize) Token(console, serial, 31);
            return true;
        }

        private static bool Accounting(BootPageAllocatorState state, ulong free, ulong allocated) =>
            state.IsInitialized && state.PageSize == 4096 && state.FreeNodeCount == 1 &&
            state.HeadNodeIndex == 0 && state.FreePageCount == free &&
            state.FreeByteCount == free * 4096 && state.AllocatedPageCount == allocated &&
            state.AllocatedByteCount == allocated * 4096;

        private static bool Same(BootPageAllocatorState a, BootPageAllocatorState b) =>
            a.IsInitialized == b.IsInitialized && a.PageSize == b.PageSize &&
            a.HeadNodeIndex == b.HeadNodeIndex && a.FreeNodeCount == b.FreeNodeCount &&
            a.FreePageCount == b.FreePageCount && a.FreeByteCount == b.FreeByteCount &&
            a.AllocatedPageCount == b.AllocatedPageCount && a.AllocatedByteCount == b.AllocatedByteCount;

        private static bool Fail(EfiSimpleTextOutputProtocol* console, EfiSerialIoProtocol* serial,
            ManagedHeapPageRangeState* heap, ulong reason)
        {
            Token(console, serial, 32); WriteUnsignedDecimal(console, serial, reason);
            Token(console, serial, 33);
            // A default failure result does not report ownership. Only the original
            // stable slot and sticky observation can report a known reservation.
            int reservation = 34;
            if (s_reservationObserved) reservation = 29;
            else if (heap != null)
            {
                if (heap->Lifecycle == ManagedHeapPageRangeLifecycle.ReservedNotReady ||
                    heap->Lifecycle == ManagedHeapPageRangeLifecycle.Ready) reservation = 29;
                else if (heap->Lifecycle == ManagedHeapPageRangeLifecycle.Uninitialized)
                {
                    bool untouched = true;
                    for (ulong i = 0; i < ManagedHeapPageRangeLiveAllocator.RequiredStateBytes; i++)
                        if (((byte*)heap)[i] != 0) untouched = false;
                    if (untouched) reservation = 30;
                }
            }
            Token(console, serial, reservation); Token(console, serial, 35);
            return false;
        }

        private static void Hex(EfiSimpleTextOutputProtocol* console, EfiSerialIoProtocol* serial, ulong value)
        {
            Write(console, serial, (byte)'0'); Write(console, serial, (byte)'x');
            for (int shift = 60; shift >= 0; shift -= 4)
            {
                byte digit = (byte)((value >> shift) & 15);
                Write(console, serial, (byte)(digit < 10 ? '0' + digit : 'A' + digit - 10));
            }
        }

        private static void Packed(EfiSimpleTextOutputProtocol* console, EfiSerialIoProtocol* serial, ulong bytes, int count)
        {
            for (int i = 0; i < count; i++)
            {
                Write(console, serial, (byte)bytes);
                bytes >>= 8;
            }
        }

