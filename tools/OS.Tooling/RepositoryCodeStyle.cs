using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace OS.Tooling;

/// <summary>Read-only, host-side C# type/file checks. Parses conditional branches
/// without executing source or loading project analyzers. Findings are deterministic;
/// malformed source fails inspection. Generated and reference trees are excluded.</summary>
public static class RepositoryCodeStyle
{
    private static readonly HashSet<string> Roots = new(StringComparer.Ordinal)
        { "src", "std", "apps", "tools", "tests" };

    public static IReadOnlyList<SourceStyleDiagnostic> Check(string root)
    {
        root = Path.GetFullPath(root);
        var result = new List<SourceStyleDiagnostic>();
        foreach (string path in RepositoryChecks.Enumerate(root))
        {
            string relative = Path.GetRelativePath(root, path).Replace('\\', '/');
            if (Path.GetExtension(path) == ".cs" && Roots.Contains(relative.Split('/')[0]))
                result.AddRange(CheckFile(relative, File.ReadAllText(path)));
        }

        return result.OrderBy(value => value.Path, StringComparer.Ordinal).ThenBy(value => value.Line)
            .ThenBy(value => value.Rule, StringComparer.Ordinal).ToArray();
    }

    public static IReadOnlyList<SourceStyleDiagnostic> CheckFile(string path, string source)
    {
        if (path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || source.AsSpan(0, Math.Min(source.Length, 256)).Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
            return [];

        var result = new HashSet<SourceStyleDiagnostic>();
        foreach (var options in CSharpSourceProfiles.ForSource(source))
        {
            var tree = CSharpSyntaxTree.ParseText(source, options, path);
            var root = tree.GetRoot();
            foreach (var diagnostic in tree.GetDiagnostics().Where(value => value.Severity == DiagnosticSeverity.Error))
                result.Add(new(path, diagnostic.Location.GetLineSpan().StartLinePosition.Line + 1,
                    "CLROSSTYLE000", diagnostic.GetMessage(System.Globalization.CultureInfo.InvariantCulture)));

            var declarations = root.DescendantNodes().OfType<MemberDeclarationSyntax>()
                .Where(IsType).Where(value => !IsContainingWrapper(value)).ToArray();
            if (declarations.Length > 1 || (declarations.Length != 0 && root.DescendantNodes().OfType<GlobalStatementSyntax>().Any()))
            {
                foreach (var declaration in declarations)
                    Add(declaration, "CLROSSTYLE001", "Place each type in its own file; partial containing wrappers are allowed.");
            }

            foreach (var declaration in declarations)
            {
                string name = TypeName(declaration);
                string file = Path.GetFileNameWithoutExtension(path);
                string[] parents = declaration.Ancestors().OfType<TypeDeclarationSyntax>()
                    .Reverse().Select(value => value.Identifier.ValueText).ToArray();
                bool matches = parents.Length != 0
                    ? file == string.Join(".", parents.Append(name))
                    : file == name || file.EndsWith("." + name, StringComparison.Ordinal)
                        || (declaration.Modifiers.Any(SyntaxKind.PartialKeyword) && file.StartsWith(name + ".", StringComparison.Ordinal));
                if (!matches)
                    Add(declaration, "CLROSSTYLE002", $"Filename must identify {string.Join(".", parents.Append(name))}; use Parent.Child.cs for helpers.");
            }
        }

        return result.OrderBy(value => value.Line).ThenBy(value => value.Rule, StringComparer.Ordinal).ToArray();

        void Add(MemberDeclarationSyntax node, string rule, string message) => result.Add(new(path,
            node.GetLocation().GetLineSpan().StartLinePosition.Line + 1, rule, message));
    }

    internal static bool IsType(MemberDeclarationSyntax node) => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax;

    internal static string TypeName(MemberDeclarationSyntax node) => node switch
    {
        BaseTypeDeclarationSyntax type => type.Identifier.ValueText,
        DelegateDeclarationSyntax type => type.Identifier.ValueText,
        _ => throw new ArgumentException("type_declaration_required", nameof(node))
    };

    private static bool IsContainingWrapper(MemberDeclarationSyntax node) => node is TypeDeclarationSyntax type
        && type.Modifiers.Any(SyntaxKind.PartialKeyword) && type.Members.Count != 0 && type.Members.All(IsType);
}
