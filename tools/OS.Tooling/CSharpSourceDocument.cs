using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace OS.Tooling;

/// <summary>A host-owned immutable read of source text, syntax and its original
/// byte identity. Parsing and hashing use the same read; no native qualification
/// follows from this snapshot.</summary>
public sealed record CSharpSourceDocument(string Path, string Sha256, SyntaxTree Syntax, bool IsGenerated = false)
{
    public string Text => Syntax.GetText().ToString();

    public static CSharpSourceDocument Read(string path, CSharpParseOptions options)
        => FromBytes(path, File.ReadAllBytes(path), options);

    internal static CSharpSourceDocument FromBytes(string path, byte[] bytes, CSharpParseOptions options)
    {
        using var stream = new MemoryStream(bytes, writable: false);
        using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: true);
        string text = reader.ReadToEnd();
        bool generated = path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || text.AsSpan(0, Math.Min(text.Length, 256)).Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
        return new(System.IO.Path.GetFullPath(path), Convert.ToHexString(SHA256.HashData(bytes)),
            CSharpSyntaxTree.ParseText(text, options, System.IO.Path.GetFullPath(path)), generated);
    }
}
