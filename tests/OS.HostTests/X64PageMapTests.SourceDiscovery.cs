using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using OS.Kernel.Memory;
using OS.Tooling;

internal static unsafe partial class X64PageMapTests
{
    private static string[] PageMapRoots() =>
    [
        typeof(X64PageMap).FullName!, typeof(X64TlbInvalidationPlan).FullName!,
        typeof(X64InvlpgStubPlan).FullName!, typeof(X64ProtectionProbeStubPlan).FullName!
    ];

    // These logical families retain the raw policy of the four original source
    // units. Discovery supplies their current files and all conditional partials.
    private static Type[][] PageMapRawFamilies() =>
    [
        [typeof(X64PageMap), typeof(X64PageMapOperation), typeof(X64PageMapStatus),
            typeof(X64PageTableImagePage), typeof(X64EssentialMappingRange),
            typeof(X64PageMapRequest), typeof(X64PageMapResult)],
        [typeof(X64TlbInvalidationPlan), typeof(X64TlbInvalidationStatus),
            typeof(X64TlbInvalidationRange), typeof(X64TlbInvalidationRecord),
            typeof(X64TlbInvalidationPlanResult)],
        [typeof(X64InvlpgStubPlan), typeof(X64InvlpgStubPhase),
            typeof(X64InvlpgStubPlanStatus), typeof(X64InvlpgStubPlanResult),
            typeof(X64InvlpgInvocationRequest), typeof(X64InvlpgInvocationPlanResult)],
        [typeof(X64ProtectionProbeStubPlan), typeof(X64ProtectionProbeStubPhase),
            typeof(X64ProtectionProbeTerminalKind), typeof(X64ProtectionProbeEventKind),
            typeof(X64ProtectionProbeStatus), typeof(X64ProtectionProbeStubPlanResult),
            typeof(X64ProtectionProbeEvent), typeof(X64ProtectionProbeObservation),
            typeof(X64ProtectionProbePlanResult)]
    ];

    private static CSharpSourceCatalog PageMapEfi() =>
        HostSourceCatalog.Efi(EfiOptions.Parse([], false).Profile());

    private static bool PageMapRawSourcePolicy(CSharpSourceCatalog host, CSharpSourceCatalog efi)
    {
        foreach (var family in PageMapRawFamilies())
        {
            var documents = HostSourceText.DocumentSources(host, family.Select(type => type.FullName!).ToArray());
            foreach (var document in documents)
            {
                RequirePageMapSourceJoin(efi, document);
                string source = document.Text;
                if (source.Contains("System.", StringComparison.Ordinal)
                    || source.Contains("Span<", StringComparison.Ordinal)
                    || source.Contains("throw ", StringComparison.Ordinal)
                    || source.Contains("delegate ", StringComparison.Ordinal)
                    || source.Contains("invlpg", StringComparison.OrdinalIgnoreCase)
                        && family.Contains(typeof(X64PageMap)))
                    return false;
            }
        }
        return true;
    }

    private static CSharpSourceDocument RequirePageMapSourceJoin(CSharpSourceCatalog efi,
        CSharpSourceDocument document)
    {
        var admitted = efi.Documents.SingleOrDefault(candidate =>
            candidate.Path.Equals(document.Path, StringComparison.OrdinalIgnoreCase));
        if (admitted is null || admitted.Sha256 != document.Sha256)
            throw new InvalidOperationException("page_map_efi_source_join " + document.Path);
        return admitted;
    }

    private static CSharpSourceDocument[] PageMapSourceClosure(string root,
        CSharpSourceCatalog host, CSharpSourceCatalog efi)
    {
        string kernelRoot = Path.Combine(root, "src", "OS.Kernel");
        string objectRoot = Path.GetFullPath(Path.Combine(kernelRoot, "obj")) + Path.DirectorySeparatorChar;
        var selected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var document in host.DependencySources(PageMapRoots()))
        {
            var syntax = document.Syntax.GetRoot();
            bool generated = document.IsGenerated || document.Text.AsSpan(0, Math.Min(document.Text.Length, 256))
                .Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
            if (generated && document.Path.StartsWith(objectRoot, StringComparison.OrdinalIgnoreCase)
                && syntax is CompilationUnitSyntax { Members.Count: 0, Externs.Count: 0 })
                continue;
            _ = EfiEvidence.RelativePath(kernelRoot, document.Path, "page_map_dependency_outside_kernel");
            var admitted = RequirePageMapSourceJoin(efi, document);
            HostNoStdLibClosure.RequirePlanningTypes(host, document);
            HostNoStdLibClosure.RequirePlanningTypes(efi, admitted);
            selected.Add(admitted.Path);
        }
        if (selected.Count == 0)
            throw new InvalidOperationException("page_map_dependency_empty");
        return efi.Documents.Where(document => selected.Contains(document.Path)).ToArray();
    }

    private static string[] NoStdLibPageMapSources(string root, string shim)
    {
        var sources = PageMapSourceClosure(root,
            HostSourceCatalog.Project("src/OS.Kernel/OS.Kernel.csproj"), PageMapEfi());
        ValidatePageMapShimClosure(sources, shim);
        foreach (var document in sources)
            AuthorityFiles.RequirePlainPath(root, document.Path, "page_map_source_link");
        return sources.Select(document => document.Path).ToArray();
    }

    private static void ValidatePageMapShimClosure(IReadOnlyList<CSharpSourceDocument> sources, string shim)
    {
        var parse = new CSharpParseOptions(LanguageVersion.CSharp14, preprocessorSymbols: ["NOSTDLIB_EFI"]);
        var shimTree = CSharpSyntaxTree.ParseText(shim, parse, "NoStdLibShim.cs");
        string[] allowed =
        [
            "System.Object", "System.ValueType", "System.Enum", "System.Delegate",
            "System.MulticastDelegate", "System.Attribute", "System.Void", "System.Boolean",
            "System.Byte", "System.SByte", "System.Int16", "System.UInt16", "System.Int32",
            "System.UInt32", "System.Int64", "System.UInt64", "System.IntPtr", "System.UIntPtr",
            "System.AttributeTargets", "System.AttributeUsageAttribute",
            "System.Runtime.CompilerServices.IsReadOnlyAttribute"
        ];
        var declarations = shimTree.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>().ToArray();
        var identities = declarations.Select(type => string.Join(".", type.Ancestors()
            .OfType<BaseNamespaceDeclarationSyntax>().Reverse().Select(space =>
                string.Concat(space.Name.DescendantTokens().Select(token => token.ValueText))))
            + "." + type.Identifier.ValueText).ToArray();
        if (!identities.Order(StringComparer.Ordinal).SequenceEqual(allowed.Order(StringComparer.Ordinal))
            || declarations.Any(type => type.Ancestors().OfType<BaseTypeDeclarationSyntax>().Any()
                || type is TypeDeclarationSyntax { TypeParameterList: not null })
            || shimTree.GetRoot().DescendantNodes().OfType<DelegateDeclarationSyntax>().Any())
            throw new InvalidOperationException("page_map_shim_surface");
        var compilation = CSharpCompilation.Create("PageMapShimClosure", sources.Select(document =>
            CSharpSyntaxTree.ParseText(document.Text, parse, document.Path)).Append(shimTree), [],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errors = compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException("page_map_shim_closure " + string.Join("; ", errors.Select(error => error.ToString())));
    }
}
