    private const string MaterializerType = "OS.Kernel.Memory.BootPageAllocatorStateMaterializer";

    private static bool TestSourceAndIntegrationBoundary()
    {
        string repositoryRoot = HostToolProcess.FindRepositoryRoot();
        var efi = HostSourceCatalog.Efi(EfiOptions.Parse([], false).Profile());
        var host = HostSourceCatalog.Project("src/OS.Kernel/OS.Kernel.csproj");
        var sources = MaterializerSources(repositoryRoot, host, efi);
        if (!CheckMaterializerSource(efi, sources))
            return false;

        Type[] podTypes = [typeof(BootPageFreeListNode), typeof(BootPageAllocatorState), typeof(BootPageAllocatorStateMaterializationResult)];
        foreach (Type type in podTypes)
        {
            foreach (FieldInfo field in type.GetFields(BindingFlags.Instance | BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly))
            {
                if (!field.FieldType.IsValueType || field.FieldType.IsPointer || field.FieldType.IsArray || field.IsStatic && !field.IsLiteral)
                    return SourceFailure("managed-field=" + type.Name + "." + field.Name);
            }
        }

        var owner = new EfiAllocatorOwnershipSources(EfiOptions.Parse(["--EnableM09004Probe"], false).Profile()).Sources;
        if (!EfiProfileTestControls.RemoveOwnedCooperativeMaterializer(owner, out var remaining, out string reason))
            return SourceFailure("owned-cooperative-materializer " + reason);
        return remaining.Values.All(text => !RemoveComments(text)
            .Contains(nameof(BootPageAllocatorStateMaterializer), StringComparison.Ordinal));
    }

    // Host dependency edges stop at metadata System types. Each first-party
    // input must also belong to the actual admitted EFI compilation with the
    // same bytes. The unchanged shim then binds the NOSTDLIB_EFI branch below.
    internal static CSharpSourceDocument[] MaterializerSources(string repositoryRoot,
        CSharpSourceCatalog host, CSharpSourceCatalog efi)
    {
        string kernelRoot = Path.Combine(repositoryRoot, "src", "OS.Kernel");
        string objectRoot = Path.GetFullPath(Path.Combine(kernelRoot, "obj")) + Path.DirectorySeparatorChar;
        var selected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var source in host.DependencySources(MaterializerType))
        {
            var declarations = source.Syntax.GetRoot().DescendantNodes()
                .Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax).ToArray();
            bool generatedHeader = source.IsGenerated || source.Text.AsSpan(0, Math.Min(source.Text.Length, 256))
                .Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
            if (generatedHeader && source.Path.StartsWith(objectRoot, StringComparison.OrdinalIgnoreCase)
                && declarations.Length == 0
                && source.Syntax.GetRoot() is CompilationUnitSyntax { Members.Count: 0, Externs.Count: 0 })
                continue;
            _ = EfiEvidence.RelativePath(kernelRoot, source.Path, "materializer_dependency_outside_kernel");
            var admitted = efi.Documents.SingleOrDefault(item => string.Equals(item.Path, source.Path, StringComparison.OrdinalIgnoreCase));
            if (admitted is null || admitted.Sha256 != source.Sha256)
                throw new InvalidOperationException("materializer_efi_source_join " + source.Path);
            var model = efi.Compilation.GetSemanticModel(admitted.Syntax);
            var types = admitted.Syntax.GetRoot().DescendantNodes()
                .Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)
                .Select(node => (INamedTypeSymbol)model.GetDeclaredSymbol(node)!).ToArray();
            if (types.Length == 0 || types.Any(type => type.ContainingNamespace.ToDisplayString() != "OS.Kernel.Memory"))
                throw new InvalidOperationException("materializer_dependency_layer " + source.Path);
            selected.Add(admitted.Path);
        }
        if (selected.Count == 0)
            throw new InvalidOperationException("materializer_dependency_empty");
        // Keep actual EFI compiler order rather than sorting filenames.
        return efi.Documents.Where(source => selected.Contains(source.Path)).ToArray();
    }

    private static string[] NoStdLibMaterializerSources(string repositoryRoot, string shim)
    {
        var efi = HostSourceCatalog.Efi(EfiOptions.Parse([], false).Profile());
        var host = HostSourceCatalog.Project("src/OS.Kernel/OS.Kernel.csproj");
        var sources = MaterializerSources(repositoryRoot, host, efi);
        ValidateMaterializerShimClosure(sources, shim);
        foreach (var source in sources)
            AuthorityFiles.RequirePlainPath(repositoryRoot, source.Path, "materializer_source_link");
        return sources.Select(source => source.Path).ToArray();
    }

    internal static void ValidateMaterializerShimClosure(IReadOnlyList<CSharpSourceDocument> sources, string shim)
    {
        var parse = new CSharpParseOptions(LanguageVersion.CSharp14, preprocessorSymbols: ["NOSTDLIB_EFI"]);
        var shimTree = CSharpSyntaxTree.ParseText(shim, parse, "NoStdLibShim.cs");
        string[] allowed = ["System.Object", "System.ValueType", "System.Enum", "System.Delegate", "System.MulticastDelegate",
            "System.Attribute", "System.Void", "System.Boolean", "System.Byte", "System.Int32", "System.UInt32",
            "System.UInt64", "System.IntPtr", "System.UIntPtr", "System.AttributeTargets", "System.AttributeUsageAttribute",
            "System.Runtime.CompilerServices.IsReadOnlyAttribute"];
        var declarations = shimTree.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>().ToArray();
        var identities = declarations.Select(type => string.Join(".", type.Ancestors().OfType<BaseNamespaceDeclarationSyntax>()
            .Reverse().Select(space => string.Concat(space.Name.DescendantTokens().Select(token => token.ValueText))))
            + "." + type.Identifier.ValueText).ToArray();
        if (identities.Length != allowed.Length || !identities.Order(StringComparer.Ordinal).SequenceEqual(allowed.Order(StringComparer.Ordinal))
            || declarations.Any(type => type.Ancestors().OfType<BaseTypeDeclarationSyntax>().Any()
                || type is TypeDeclarationSyntax { TypeParameterList: not null })
            || shimTree.GetRoot().DescendantNodes().OfType<DelegateDeclarationSyntax>().Any())
            throw new InvalidOperationException("materializer_shim_surface");
        var syntax = sources.Select(source => CSharpSyntaxTree.ParseText(source.Text, parse, source.Path)).Append(shimTree);
        var compilation = CSharpCompilation.Create("MaterializerShimClosure", syntax, [],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errors = compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException("materializer_shim_closure " + string.Join("; ", errors.Select(error => error.ToString())));
    }

    internal static bool CheckMaterializerSource(CSharpSourceCatalog source, IReadOnlyList<CSharpSourceDocument> documents)
    {
        string[] forbiddenPatterns = [@"\bReadOnlySpan\s*<", @"\bSpan\s*<", @"\bstring\b", @"\bthrow\b", @"\bException\b", @"\bSystem\.Reflection\b", @"\bSystem\.Linq\b", @"\bdelegate\b", @"\bTask\b", @"\bThread\b", @"\bConsole\b", @"\bGC\.", @"\bBootPageFreeListPlanResult\b", @"\bBootPageAllocatorPlanResult\b", @"\bBootMemoryRegionPlan\b", @"\bBootPageAllocatorStateInitializer\b", @"\bBootPageFreeListBuilder\b", @"\bEfiEntry\b", @"\bBootSequence\b", @"\bulong\.MaxValue\b", @"\bCLROS_" + @"M01_006_READY\b"];
        foreach (var document in documents)
            foreach (string pattern in forbiddenPatterns)
                if (Regex.IsMatch(RemoveComments(document.Text), pattern, RegexOptions.CultureInvariant))
                    return SourceFailure("forbidden=" + pattern);

        var materializer = source.Type(MaterializerType);
        var node = source.Type("OS.Kernel.Memory.BootPageFreeListNode");
        var state = source.Type("OS.Kernel.Memory.BootPageAllocatorState");
        var materialize = source.Method(MaterializerType, "Materialize");
        var method = source.Compilation.GetSemanticModel(materialize.SyntaxTree).GetDeclaredSymbol(materialize)!;
        bool Parameter(string name, ITypeSymbol? pointed = null) => method.Parameters.SingleOrDefault(parameter => parameter.Name == name)
            is { RefKind: RefKind.None } value && (pointed is null ? value.Type.SpecialType == SpecialType.System_UInt64
                : value.Type is IPointerTypeSymbol pointer && SymbolEqualityComparer.Default.Equals(pointer.PointedAtType, pointed));
        var maximum = materializer.GetMembers("MaximumUnsignedLong").OfType<IFieldSymbol>().Single();
        var succeeded = source.Type("OS.Kernel.Memory.BootPageAllocatorStateMaterializationResult").GetMembers("Succeeded")
            .OfType<IPropertySymbol>().Single().DeclaringSyntaxReferences.Single().GetSyntax();
        bool summary = succeeded.DescendantNodes().OfType<InvocationExpressionSyntax>().Any(call =>
            source.Invocation(call) is { Name: "IsRepresentableSuccessSummary" } target
            && SymbolEqualityComparer.Default.Equals(target.ContainingType, materializer));
        if (node.TypeKind != TypeKind.Struct || !node.IsReadOnly || node.DeclaredAccessibility != Accessibility.Public
            || state.TypeKind != TypeKind.Struct || !state.IsReadOnly || state.DeclaredAccessibility != Accessibility.Public
            || !method.IsStatic || method.DeclaredAccessibility != Accessibility.Public || method.Arity != 0
            || !SymbolEqualityComparer.Default.Equals(method.ReturnType, source.Type("OS.Kernel.Memory.BootPageAllocatorStateMaterializationResult"))
            || !BooleanSignature("TryValidatePointerAndSummaryMetadata", Accessibility.Private)
            || !BooleanSignature("IsRepresentableSuccessSummary", Accessibility.Internal)
            || !Parameter("sourceNodes", node) || !Parameter("sourceNodeCount") || !Parameter("sourceNodeCapacity")
            || !Parameter("sourceRangeCount") || !Parameter("destinationState", state)
            || !maximum.IsConst || maximum.DeclaredAccessibility != Accessibility.Private
            || maximum.ConstantValue is not ulong.MaxValue
            || !SizeProperty("ActualSourceNodeStructureSize", node) || !SizeProperty("ActualDestinationStateStructureSize", state) || !summary)
            return SourceFailure("required-contract");

        if (!OrderedMaterializerFragments(materialize, ["TryValidatePointerAndSummaryMetadata(", "BootPageFreeListNode node = sourceNodes[currentNodeIndex]", "if (observedFreePages != expectedFreePages)", "if (observedFreeBytes != expectedFreeBytes)", "destinationState[0] = state"])
            || !OrderedMaterializerFragments(source.Method(MaterializerType, "TryValidatePointerAndSummaryMetadata"), ["if (sourceNodeCount == 0)", "SourceNodeTableByteCountOverflow", "if (sourceNodeCount > MaximumSourceNodeCount)", "if (sourceNodeCapacity < sourceNodeCount)", "if (sourceNodeAddress == 0)", "MisalignedSourceNodes", "SourceNodeTableAddressRangeOverflow", "DestinationStateCapacityTooSmall", "DestinationStateByteCountOverflow", "if (destinationStateAddress == 0)", "MisalignedDestinationState", "DestinationStateAddressRangeOverflow", "DestinationOverlapsSourceNodes", "if (pageSize != RequiredPageSize)", "InvalidSourceRangeCount", "InvalidHeadNodeIndex", "if (expectedFreePages == 0)", "ExpectedByteCountOverflow", "ExpectedByteCountMismatch"])
            || !OrderedMaterializerFragments(source.Method(MaterializerType, "IsRepresentableSuccessSummary"), ["ActualSourceNodeStructureSize", "ActualDestinationStateStructureSize", "BootPageFreeListNode.StructureSize", "BootPageAllocatorState.StructureSize", "sourceNodeCount", "sourceNodeCapacity", "destinationStateCapacity", "pageSize == RequiredPageSize", "expectedFreePages != 0", "expectedFreePages * pageSize == expectedFreeBytes"]))
            return SourceFailure("validation-order");
        return true;

        bool BooleanSignature(string name, Accessibility accessibility)
        {
            var declaration = source.Method(MaterializerType, name);
            var symbol = source.Compilation.GetSemanticModel(declaration.SyntaxTree).GetDeclaredSymbol(declaration)!;
            return symbol.IsStatic && symbol.Arity == 0 && symbol.DeclaredAccessibility == accessibility
                && symbol.ReturnType.SpecialType == SpecialType.System_Boolean;
        }

        bool SizeProperty(string name, INamedTypeSymbol type)
        {
            var syntax = (PropertyDeclarationSyntax)materializer.GetMembers(name).OfType<IPropertySymbol>().Single()
                .DeclaringSyntaxReferences.Single().GetSyntax();
            return syntax.ExpressionBody is { Expression: var expression }
                && source.Compilation.GetSemanticModel(syntax.SyntaxTree).GetOperation(expression)
                    is IConversionOperation { Type.SpecialType: SpecialType.System_UInt64, Operand: ISizeOfOperation size }
                && SymbolEqualityComparer.Default.Equals(size.TypeOperand, type);
        }
    }

    private static bool OrderedMaterializerFragments(MethodDeclarationSyntax method, string[] fragments)
    {
        var tokens = (method.Body as SyntaxNode ?? method.ExpressionBody!).DescendantTokens().ToArray();
        int cursor = 0;
        foreach (string fragment in fragments)
        {
            var expected = SyntaxFactory.ParseTokens(fragment).Where(token => !token.IsKind(SyntaxKind.EndOfFileToken)).ToArray();
            bool found = false;
            for (; cursor <= tokens.Length - expected.Length; cursor++)
                if (tokens.Skip(cursor).Take(expected.Length).Zip(expected).All(pair => pair.First.RawKind == pair.Second.RawKind && pair.First.Text == pair.Second.Text))
                {
                    cursor += expected.Length;
                    found = true;
                    break;
                }
            if (!found)
                return false;
        }
        return true;
    }

