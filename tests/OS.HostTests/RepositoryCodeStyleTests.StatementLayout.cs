using OS.Tooling;

internal static partial class RepositoryCodeStyleTests
{
    [HostTest("source style rejects compact executable blocks and control bodies")]
    private static void CompactStatementLayout()
    {
        foreach (string statements in new[]
        {
            "First(); Second();",
            "if (true) First();",
            "if (true)\n    First(); else\n    Second();",
            "for (int i = 0; i < 2; i++) First();",
            "foreach (var item in items) First();",
            "while (true) First();",
            "do First(); while (false);",
            "using (var item = Open()) First();",
            "lock (gate) First();",
            "fixed (int* item = values) First();",
            "try\n{\n    First();\n} catch\n{\n    Second();\n}",
            "try\n{\n    First();\n} finally\n{\n    Second();\n}",
            "try\n{\n    First();\n}\nfinally {\n    Second();\n}",
            "try\n{\n    First();\n}\nfinally\n{ Second();\n}",
            "try\n{\n    First();\n}\nfinally\n{\n    First(); Second();\n}",
            "switch (value)\n{\n    case 1: First();\n        break;\n}",
            "switch (value) {\n    default:\n        break;\n}",
            "switch (value)\n{\n    case 1: case 2:\n        break;\n}",
            "Action run = () => {\n    First();\n};",
            "{\n    First(); }",
            "{}"
        })
        {
            // Keep the enclosing method fully expanded so each case must catch
            // its own boundary, rather than an unrelated wrapper violation.
            string source = "class Owner\n{\n    void Run()\n    {\n" + statements + "\n    }\n}";
            var findings = RepositoryCodeStyle.CheckFile("Owner.cs", source);
            HostCheck.True(findings.All(finding => finding.Rule != "CLROSSTYLE000"), statements);
            HostCheck.Equal(1, findings.Count(finding => finding.Rule == "CLROSSTYLE004"), statements);
        }

        HostCheck.Equal(1, RepositoryCodeStyle.CheckFile("Owner.cs", "class Owner\n{\n    void Run() {\n    }\n}")
            .Count(finding => finding.Rule == "CLROSSTYLE004"), "method brace boundary");
    }

    [HostTest("source style preserves concise expressions and for header separators")]
    private static void ExpandedStatementLayout()
    {
        const string source = """
            class Owner
            {
                int Next(int value) => value + 1;
                void Run(bool ready)
                {
                    for (int i = 0; i < 2; i++)
                        Next(i);
                    if (ready)
                        Next(0);
                    else if (!ready)
                        Next(1);
                    else
                    {
                    }
                    try
                    {
                        Next(2);
                    }
                    finally
                    {
                        Next(3);
                        Next(4);
                    }
                    switch (ready)
                    {
                        case true:
                            Next(5);
                            break;
                        default:
                            break;
                    }
                }
            }
            """;
        HostCheck.Equal(0, RepositoryCodeStyle.CheckFile("Owner.cs", source).Count);
    }

    [HostTest("source layout ignores literal contents comments and generated files")]
    private static void StatementLayoutLiterals()
    {
        const string source = """"
            class Owner
            {
                void Run()
                {
                    string ordinary = "if (ready) First(); Second();";
                    string raw = """
                        finally { First(); Second(); }
                        """;
                    // while (ready) First(); Second();
                    /* finally { First(); Second(); } */
                }
            }
            """";
        HostCheck.Equal(0, RepositoryCodeStyle.CheckFile("Owner.cs", source).Count);
        HostCheck.Equal(0, RepositoryCodeStyle.CheckFile("Owner.g.cs", "class Owner { void Run() { First(); Second(); } }").Count);
        HostCheck.Equal(0, RepositoryCodeStyle.CheckFile("Owner.cs", "// <auto-generated/>\nclass Owner { void Run() { First(); Second(); } }").Count);
    }

    [HostTest("source layout covers conditional bodies and top level programs")]
    private static void ConditionalStatementLayout()
    {
        const string source = """
            class Owner
            {
                void Run()
                {
            #if HIDDEN
                    First(); Second();
            #endif
                }
            }
            """;
        HostCheck.True(RepositoryCodeStyle.CheckFile("Owner.cs", source).Any(finding => finding.Rule == "CLROSSTYLE004"));
        HostCheck.True(RepositoryCodeStyle.CheckFile("Program.cs", "First(); Second();").Any(finding => finding.Rule == "CLROSSTYLE004"));
        HostCheck.Equal(0, RepositoryCodeStyle.CheckFile("Program.cs", "First();\nSecond();\n").Count);
    }
}
