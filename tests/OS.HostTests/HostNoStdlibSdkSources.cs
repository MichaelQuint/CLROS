using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using OS.Tooling;

/// <summary>Builds bounded host SDK inputs with the complete reviewed minimal
/// runtime shim. Fixtures supply their root, permitted runtime owners and assembly
/// identity. Kernel inputs must match actual EFI bytes; unrelated runtime services
/// reject. This source/managed-compilation check does not qualify native execution.</summary>
internal static class HostNoStdlibSdkSources
{
    private static void RequireKernelLayer(CSharpSourceCatalog catalog, CSharpSourceDocument document,
        bool requireType, Type[] permittedRuntimeOwners, string diagnosticPrefix)
    {
        var model = catalog.Compilation.GetSemanticModel(document.Syntax);
        var permittedRuntime = permittedRuntimeOwners.Select(type => type.FullName!).ToHashSet(StringComparer.Ordinal);
        var declarations = document.Syntax.GetRoot().DescendantNodes()
            .Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax).ToArray();
        if (requireType && declarations.Length == 0)
            throw new InvalidOperationException(diagnosticPrefix + "_dependency_no_type " + document.Path);
        foreach (var declaration in declarations)
        {
            var type = (INamedTypeSymbol)model.GetDeclaredSymbol(declaration)!;
            while (type.ContainingType is not null)
                type = type.ContainingType;
            string space = type.ContainingNamespace.ToDisplayString();
            if (space is not ("OS.Boot" or "OS.Kernel.Memory") && !permittedRuntime.Contains(type.ToDisplayString())
                || type.Name is "BootSequence" or "EfiEntry" or "Probes")
                throw new InvalidOperationException(diagnosticPrefix + "_dependency_layer " + type.ToDisplayString());
        }
    }

    internal static CSharpSourceDocument[] Select(string root, CSharpSourceCatalog kernel, CSharpSourceCatalog efi,
        Type rootType, Type[] permittedRuntimeOwners, string diagnosticPrefix)
    {
        string kernelRoot = Path.GetFullPath(Path.Combine(root, "src", "OS.Kernel"));
        string objectRoot = Path.Combine(kernelRoot, "obj") + Path.DirectorySeparatorChar;
        var selected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var document in kernel.DependencySources(rootType.FullName!))
        {
            var syntax = document.Syntax.GetRoot();
            bool generated = document.IsGenerated
                || document.Text.AsSpan(0, Math.Min(document.Text.Length, 256)).Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
            // The original SDK fixture disables host assembly/target-framework
            // metadata and implicit imports. It still includes all actual types.
            if (generated && document.Path.StartsWith(objectRoot, StringComparison.OrdinalIgnoreCase)
                && syntax is CompilationUnitSyntax { Members.Count: 0, Externs.Count: 0 })
                continue;
            _ = EfiEvidence.RelativePath(kernelRoot, document.Path, diagnosticPrefix + "_dependency_outside_kernel");
            var admitted = efi.Documents.SingleOrDefault(value => value.Path.Equals(document.Path, StringComparison.OrdinalIgnoreCase));
            if (admitted is null || admitted.Sha256 != document.Sha256)
                throw new InvalidOperationException(diagnosticPrefix + "_efi_source_join " + document.Path);
            RequireKernelLayer(kernel, document, true, permittedRuntimeOwners, diagnosticPrefix);
            RequireKernelLayer(efi, admitted, false, permittedRuntimeOwners, diagnosticPrefix);
            selected.Add(admitted.Path);
        }

        if (selected.Count == 0)
            throw new InvalidOperationException(diagnosticPrefix + "_kernel_empty");

        // Preserve the fixture's complete reviewed runtime shim. Compiler
        // dependency discovery must not silently replace it with a smaller shim.
        string efiRoot = Path.Combine(root, "src", "OS");
        var runtime = EfiContracts.SourceAdmissionReasons
            .Where(pair => pair.Value == "reviewed_minimal_runtime_source_identity")
            .Select(pair => Path.GetFullPath(pair.Key, efiRoot)).ToHashSet(StringComparer.OrdinalIgnoreCase);
        if (runtime.Count == 0 || runtime.Any(path => !efi.Documents.Any(document => document.Path.Equals(path, StringComparison.OrdinalIgnoreCase))))
            throw new InvalidOperationException(diagnosticPrefix + "_runtime_family_missing");
        selected.UnionWith(runtime);

        string[] attributeOwners =
        [
            typeof(System.Runtime.CompilerServices.MethodImplAttribute).FullName!,
            typeof(System.Runtime.CompilerServices.MethodImplOptions).FullName!
        ];
        foreach (string owner in attributeOwners)
        {
            foreach (var document in efi.TypeSources(owner))
            {
                _ = EfiEvidence.RelativePath(Path.Combine(efiRoot, "Runtime"), document.Path, diagnosticPrefix + "_attribute_outside_runtime");
                var model = efi.Compilation.GetSemanticModel(document.Syntax);
                foreach (var declaration in document.Syntax.GetRoot().DescendantNodes()
                    .Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax))
                    if (model.GetDeclaredSymbol(declaration) is not INamedTypeSymbol type
                        || !attributeOwners.Contains(type.ToDisplayString(), StringComparer.Ordinal))
                        throw new InvalidOperationException(diagnosticPrefix + "_attribute_layer");
                selected.Add(document.Path);
            }
        }

        return efi.Documents.Where(document => selected.Contains(document.Path)).ToArray();
    }

    internal static CSharpCompilation Compile(IReadOnlyList<CSharpSourceDocument> sources,
        string assemblyName, string diagnosticPrefix)
    {
        var parse = new CSharpParseOptions(LanguageVersion.CSharp14, preprocessorSymbols: ["NOSTDLIB_EFI"]);
        var compilation = CSharpCompilation.Create(assemblyName,
            sources.Select(source => CSharpSyntaxTree.ParseText(source.Text, parse, source.Path)), [],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true,
                optimizationLevel: OptimizationLevel.Release, generalDiagnosticOption: ReportDiagnostic.Error));
        var errors = compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException(diagnosticPrefix + "_nostdlib_binding " + string.Join("; ", errors.Select(error => error.ToString())));
        return compilation;
    }
}
