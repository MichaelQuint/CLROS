    private static Type[] PolicyRawOwners() => [typeof(PageZeroMappingPolicy), typeof(PageZeroMappingPolicyOperation), typeof(PageZeroMappingPolicyStatus), typeof(PageZeroMappingIntent), typeof(PageZeroMappingPolicyResult)];

    private static Type[] PlanRawOwners() => [typeof(NullPageFaultProbePlan), typeof(NullPageFaultProbePlanStatus), typeof(NullPageFaultAccessKind), typeof(NullPageFaultProbeRequest), typeof(NullPageFaultProbePlanResult)];

    private static Type[] PageZeroHostOwners() => [typeof(PageZeroMappingPolicyTests), typeof(M01015TestData), typeof(M01015PageZeroFixture)];

    private static string PageZeroRaw(CSharpSourceCatalog source, Type[] owners) => HostSourceText.Documents(source, owners.Select(owner => owner.FullName!).ToArray());

    private static CSharpEfiProjectEvaluation PageZeroEfi(string workload) => HostSourceCatalog.EfiEvaluation(EfiOptions.Parse([], false).Profile(), workload: workload, queryTimeoutSeconds: 60);

    private static void PageZeroLayer(CSharpSourceCatalog source, CSharpSourceDocument document)
    {
        var allowedPlans = PlanRawOwners().Select(owner => owner.FullName!).ToHashSet(StringComparer.Ordinal);
        var model = source.Compilation.GetSemanticModel(document.Syntax);
        var declarations = document.Syntax.GetRoot().DescendantNodes().Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax).ToArray();
        if (declarations.Length == 0)
            throw new InvalidOperationException("page_zero_dependency_no_type");
        foreach (var declaration in declarations)
        {
            var type = (INamedTypeSymbol)model.GetDeclaredSymbol(declaration)!;
            while (type.ContainingType is not null)
                type = type.ContainingType;
            string space = type.ContainingNamespace.ToDisplayString();
            if (space is not ("OS.Boot" or "OS.Kernel.Memory") && !allowedPlans.Contains(type.ToDisplayString()) || type.Name is "BootSequence" or "EfiEntry" or "Probes")
                throw new InvalidOperationException("page_zero_dependency_layer " + type.ToDisplayString());
        }
    }

    private static CSharpSourceDocument PageZeroJoin(CSharpSourceCatalog efi, CSharpSourceDocument document)
    {
        var admitted = efi.Documents.SingleOrDefault(value => value.Path.Equals(document.Path, StringComparison.OrdinalIgnoreCase));
        if (admitted is null || admitted.Sha256 != document.Sha256)
            throw new InvalidOperationException("page_zero_efi_source_join " + document.Path);
        return admitted;
    }

    private static CSharpSourceDocument[] PageZeroSources(string root, CSharpSourceCatalog host, CSharpSourceCatalog efi)
    {
        string kernelRoot = Path.GetFullPath(Path.Combine(root, "src", "OS.Kernel"));
        string objectRoot = Path.Combine(kernelRoot, "obj") + Path.DirectorySeparatorChar;
        foreach (var document in HostSourceText.DocumentSources(host, PolicyRawOwners().Concat(PlanRawOwners()).Select(owner => owner.FullName!).ToArray()))
            _ = PageZeroJoin(efi, document);
        var selected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var document in host.DependencySources(typeof(PageZeroMappingPolicy).FullName!, typeof(NullPageFaultProbePlan).FullName!))
        {
            var syntax = document.Syntax.GetRoot();
            bool generated = document.IsGenerated || document.Text.AsSpan(0, Math.Min(document.Text.Length, 256)).Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
            if (generated && document.Path.StartsWith(objectRoot, StringComparison.OrdinalIgnoreCase) && syntax is CompilationUnitSyntax { Members.Count: 0, Externs.Count: 0 })
                continue;
            _ = EfiEvidence.RelativePath(kernelRoot, document.Path, "page_zero_dependency_outside_kernel");
            var admitted = PageZeroJoin(efi, document);
            PageZeroLayer(host, document);
            PageZeroLayer(efi, admitted);
            selected.Add(admitted.Path);
        }

        if (selected.Count == 0)
            throw new InvalidOperationException("page_zero_dependency_empty");
        return efi.Documents.Where(document => selected.Contains(document.Path)).ToArray();
    }

    private static void ValidatePageZeroShim(IReadOnlyList<CSharpSourceDocument> sources, string shim)
    {
        var parse = new CSharpParseOptions(LanguageVersion.CSharp14, preprocessorSymbols: ["NOSTDLIB_EFI"]);
        var shimTree = CSharpSyntaxTree.ParseText(shim, parse, "NoStdLibShim.cs");
        string[] allowed = ["System.Object", "System.ValueType", "System.Enum", "System.Delegate", "System.MulticastDelegate", "System.Attribute", "System.Void", "System.Boolean", "System.Byte", "System.SByte", "System.Int16", "System.UInt16", "System.Int32", "System.UInt32", "System.Int64", "System.UInt64", "System.IntPtr", "System.UIntPtr", "System.AttributeTargets", "System.AttributeUsageAttribute", "System.Runtime.CompilerServices.IsReadOnlyAttribute"];
        var declarations = shimTree.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>().ToArray();
        var identities = declarations.Select(type => string.Join(".", type.Ancestors().OfType<BaseNamespaceDeclarationSyntax>().Reverse().Select(space => string.Concat(space.Name.DescendantTokens().Select(token => token.ValueText)))) + "." + type.Identifier.ValueText).ToArray();
        if (!identities.Order(StringComparer.Ordinal).SequenceEqual(allowed.Order(StringComparer.Ordinal)) || declarations.Any(type => type.Ancestors().OfType<BaseTypeDeclarationSyntax>().Any() || type is TypeDeclarationSyntax { TypeParameterList: not null }) || shimTree.GetRoot().DescendantNodes().OfType<DelegateDeclarationSyntax>().Any())
            throw new InvalidOperationException("page_zero_shim_surface");
        var compilation = CSharpCompilation.Create("PageZeroShimClosure", sources.Select(document => CSharpSyntaxTree.ParseText(document.Text, parse, document.Path)).Append(shimTree), [], new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errors = compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException("page_zero_shim_closure " + string.Join("; ", errors.Select(error => error.ToString())));
    }

    private static string[] NoStdLibPageZeroSources(string root, string shim)
    {
        var sources = PageZeroSources(root, HostSourceCatalog.Project("src/OS.Kernel/OS.Kernel.csproj"), PageZeroEfi("SingleMinimalApi").Sources);
        ValidatePageZeroShim(sources, shim);
        foreach (var source in sources)
            AuthorityFiles.RequirePlainPath(root, source.Path, "page_zero_source_link");
        return sources.Select(document => Path.GetRelativePath(root, document.Path)).ToArray();
    }

    private static bool PageZeroProfileBoundary(string root, CSharpSourceCatalog kernel, CSharpSourceCatalog host, string workload)
    {
        var evaluation = PageZeroEfi(workload);
        var source = evaluation.Sources;
        using var parsed = System.Text.Json.JsonDocument.Parse(evaluation.EvaluationJson);
        var properties = parsed.RootElement.GetProperty("Properties");
        var items = parsed.RootElement.GetProperty("Items");
        if (properties.GetProperty("Configuration").GetString() != "Release" || properties.GetProperty("OSWorkloadProfile").GetString() != workload || items.GetProperty("Reference").GetArrayLength() != 0 || items.GetProperty("ProjectReference").GetArrayLength() != 0 || source.Compilation.References.Any())
            return false;
        var compile = items.GetProperty("Compile").EnumerateArray().ToArray();
        if (compile.Length == 0 || compile.Any(item => string.IsNullOrEmpty(item.GetProperty("Identity").GetString()) || !Path.IsPathFullyQualified(item.GetProperty("FullPath").GetString() ?? "")) || !compile.Select(item => Path.GetFullPath(item.GetProperty("FullPath").GetString()!)).SequenceEqual(source.Documents.Select(document => Path.GetFullPath(document.Path)), StringComparer.OrdinalIgnoreCase))
            return false;
        var hostPaths = HostSourceText.DocumentSources(host, PageZeroHostOwners().Select(owner => owner.FullName!).ToArray()).Select(document => document.Path).ToHashSet(StringComparer.OrdinalIgnoreCase);
        if (PageZeroHostOwners().Any(owner => source.Compilation.GetTypeByMetadataName(owner.FullName!) is not null) || source.Documents.Any(document => hostPaths.Contains(document.Path)))
            return false;
        _ = PageZeroSources(root, kernel, source);
        return source.Type("OS.Boot.EfiEntry").TypeKind == TypeKind.Class && source.Type("System.Object").SpecialType == SpecialType.System_Object;
    }

    private static bool PageZeroRawPolicy(CSharpSourceCatalog kernel, CSharpSourceCatalog host)
    {
        string policyRaw = PageZeroRaw(kernel, PolicyRawOwners());
        string planRaw = PageZeroRaw(kernel, PlanRawOwners());
        string policy = SanitizeCSharpSource(policyRaw, out bool policyHasStringLiteral, out bool policyHasInterpolatedString);
        string plan = SanitizeCSharpSource(planRaw, out bool planHasStringLiteral, out bool planHasInterpolatedString);
        if (policyHasStringLiteral || policyHasInterpolatedString || planHasStringLiteral || planHasInterpolatedString)
        {
            Console.WriteLine("M01_015_SOURCE_DIAGNOSTIC managed_literal");
            return false;
        }

        string compactPolicy = RemoveWhitespace(policy);
        string compactPlan = RemoveWhitespace(plan);
        string[] commonForbidden = ["System.", "Span<", "ReadOnlySpan<", "throw", "catch", "finally", " string ", " object ", " dynamic ", "typeof", "Reflection", "Func<", "Action<", "delegate", "stackalloc", "Runtime" + "Import", "Runtime" + "Export", "Dll" + "Import", "Library" + "Import", "Unmanaged" + "CallersOnly", "Native" + "Library", "Marshal", "GetDelegateFor" + "FunctionPointer", "Dynamic" + "Invoke", ".Invoke(", "Efi" + "Entry", "Boot" + "Sequence", "Probes."];
        foreach (string token in commonForbidden)
        {
            if (policy.Contains(token, StringComparison.Ordinal) || plan.Contains(token, StringComparison.Ordinal) || compactPolicy.Contains(RemoveWhitespace(token), StringComparison.Ordinal) || compactPlan.Contains(RemoveWhitespace(token), StringComparison.Ordinal))
            {
                Console.WriteLine("M01_015_SOURCE_DIAGNOSTIC token=" + Normalize(token));
                return false;
            }
        }

        string[] planForbidden = ["unsafe", "Unsafe.", "MemoryMarshal", "NativeMemory", "Volatile.", "Interlocked.", "Buffer.MemoryCopy", "FaultProbe" + "StubPlan", "FaultProbe" + "StubKind", "Null" + "Write", "Executable" + "Stub", "delegate" + "*", "Function" + "Pointer", "calli", "byte[", "new byte", "0xC6", "0xc6", "C6 04 " + "25", "->"];
        foreach (string token in planForbidden)
        {
            if (plan.Contains(token, StringComparison.Ordinal) || compactPlan.Contains(RemoveWhitespace(token), StringComparison.Ordinal))
            {
                return false;
            }
        }

        string testSource = HostSourceText.Documents(host, PageZeroHostOwners().Select(owner => owner.FullName!).ToArray());
        if (ContainsUnsafeNullPointerUse(testSource))
            return false;
        return policy.Contains("PerformsLiveMutation = false", StringComparison.Ordinal) && policy.Contains("WritesTableImage = false", StringComparison.Ordinal) && plan.Contains("DereferencesPageZero = false", StringComparison.Ordinal) && plan.Contains("ExecutesProbe = false", StringComparison.Ordinal);
    }

    private static bool PageZeroMarkerBoundary(string root, CSharpSourceCatalog host)
    {
        var owners = HostSourceText.DocumentSources(host, PageZeroHostOwners().Select(owner => owner.FullName!).ToArray());
        foreach (var document in owners)
            if (CSharpSourceDocument.Read(document.Path, (CSharpParseOptions)document.Syntax.Options).Sha256 != document.Sha256)
                throw new InvalidOperationException("page_zero_marker_source_changed");
        var ownerPaths = owners.Select(document => Path.GetFullPath(document.Path)).ToHashSet(StringComparer.OrdinalIgnoreCase);
        int readyOwners = 0;
        string[] roots = ["src", "std", "apps", "tools", "tests", "scripts", Path.Combine(".gitea", "workflows")];
        foreach (string relativeRoot in roots)
        {
            string scanRoot = Path.Combine(root, relativeRoot);
            if (!Directory.Exists(scanRoot))
                continue;
            foreach (string file in Directory.EnumerateFiles(scanRoot, "*", SearchOption.AllDirectories))
            {
                string normalized = file.Replace('\\', '/');
                if (normalized.Contains("/bin/", StringComparison.Ordinal) || normalized.Contains("/obj/", StringComparison.Ordinal) || normalized.Contains("/artifacts/", StringComparison.Ordinal))
                {
                    continue;
                }

                string content;
                try
                {
                    content = File.ReadAllText(file);
                }
                catch
                {
                    Console.WriteLine("M01_015_MARKER_DIAGNOSTIC unreadable=" + Path.GetFileName(file));
                    return false;
                }

                int count = CountOccurrences(content, ReadyMarker);
                if (count != 0)
                {
                    if (!ownerPaths.Contains(Path.GetFullPath(file)) || count != 1)
                    {
                        return false;
                    }

                    readyOwners++;
                }
            }
        }

        string owner = HostSourceText.Documents(host, PageZeroHostOwners().Select(type => type.FullName!).ToArray());
        return readyOwners == 1 && !owner.Contains("OS_" + "BOOT_OK", StringComparison.Ordinal) && !owner.Contains("OS_" + "SMOKE_PASS", StringComparison.Ordinal) && !owner.Contains("OS_" + "SMOKE_FAIL", StringComparison.Ordinal);
    }
