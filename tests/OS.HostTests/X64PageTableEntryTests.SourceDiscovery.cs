    private static Type[] PageEntryRawOwners() =>
    [
        typeof(PageProtection), typeof(PageCachePolicy), typeof(X64PageTableEntry),
        typeof(X64PageTableLevel), typeof(X64PageTableEntryKind), typeof(X64HardwareStatePolicy),
        typeof(X64PageTableEntryStatus), typeof(X64PatMappingToken), typeof(X64PageTableEncodingPreconditions),
