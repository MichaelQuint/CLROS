    ];

    private static CSharpEfiProjectEvaluation PageEntryEfi(string workload) =>
        HostSourceCatalog.EfiEvaluation(EfiOptions.Parse([], false).Profile(), workload: workload, queryTimeoutSeconds: 60);

    private static bool PageEntryRawPolicy(CSharpSourceCatalog source)
    {
        string core = string.Join("\n", HostSourceText.DocumentSources(source,
            PageEntryRawOwners().Select(type => type.FullName!).ToArray()).Select(document => RemoveComments(document.Text)));
        string[] forbiddenFragments = ["using System;", "System.FlagsAttribute", "[Flags", "Span<", "ReadOnlySpan<", "throw ", "try {", "catch ", "finally", "typeof(", "dynamic ", "OSHostPageProtection", "DmaMapping", "EfiEntry", "BootSequence", "RuntimeExport", "ulong.MaxValue"];
        return !forbiddenFragments.Any(fragment => core.Contains(fragment, StringComparison.Ordinal))
            && !Regex.IsMatch(core, @"\b(string|String|object|Object)\b", RegexOptions.CultureInvariant)
            && core.Contains("~0UL", StringComparison.Ordinal)
            && core.Contains("unsafe X64PageTableEntryBatchResult TryEncodeMany(", StringComparison.Ordinal)
            && core.Contains("sourceCapacity", StringComparison.Ordinal)
            && core.Contains("destinationCapacity", StringComparison.Ordinal)
            && core.Contains("sizeof(X64PageTableEntryRequest)", StringComparison.Ordinal)
            && !core.Contains("stackalloc X64PageTableEntry", StringComparison.Ordinal);
    }

    private static bool PageEntryEnumBoundary(string root, CSharpSourceCatalog source)
    {
        var declaration = source.Type(typeof(X64PageTableLevel).FullName!).DeclaringSyntaxReferences.Single().GetSyntax();
        var document = source.Document(declaration);
        string[] productionFiles = Directory.EnumerateFiles(Path.Combine(root, "src"), "*.cs", SearchOption.AllDirectories)
            .Where(path => !HasDirectorySegment(path, "bin") && !HasDirectorySegment(path, "obj")).ToArray();
        string[] levelDeclarations = productionFiles.Where(path => Regex.IsMatch(RemoveComments(File.ReadAllText(path)),
            @"\benum\s+X64PageTableLevel\b", RegexOptions.CultureInvariant)).ToArray();
        return levelDeclarations.Length == 1
            && Path.GetFullPath(levelDeclarations[0]).Equals(Path.GetFullPath(document.Path), StringComparison.OrdinalIgnoreCase)
            && CSharpSourceDocument.Read(document.Path, (CSharpParseOptions)document.Syntax.Options).Sha256 == document.Sha256;
    }

    private static CSharpSourceDocument RequirePageEntryJoin(CSharpSourceCatalog efi, CSharpSourceDocument document)
    {
        var admitted = efi.Documents.SingleOrDefault(candidate => candidate.Path.Equals(document.Path, StringComparison.OrdinalIgnoreCase));
        if (admitted is null || admitted.Sha256 != document.Sha256)
            throw new InvalidOperationException("page_entry_efi_source_join " + document.Path);
        return admitted;
    }

    private static CSharpSourceDocument[] PageEntrySources(string root, CSharpSourceCatalog host, CSharpSourceCatalog efi)
    {
        string kernelRoot = Path.Combine(root, "src", "OS.Kernel");
        string objectRoot = Path.GetFullPath(Path.Combine(kernelRoot, "obj")) + Path.DirectorySeparatorChar;
        foreach (var document in HostSourceText.DocumentSources(host, PageEntryRawOwners().Select(type => type.FullName!).ToArray()))
            _ = RequirePageEntryJoin(efi, document);
        var selected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var document in host.DependencySources(typeof(X64PageTableEntry).FullName!,
            typeof(PageProtection).FullName!, typeof(PageCachePolicy).FullName!))
        {
            var syntax = document.Syntax.GetRoot();
            bool generated = document.IsGenerated || document.Text.AsSpan(0, Math.Min(document.Text.Length, 256))
                .Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
            if (generated && document.Path.StartsWith(objectRoot, StringComparison.OrdinalIgnoreCase)
                && syntax is CompilationUnitSyntax { Members.Count: 0, Externs.Count: 0 })
                continue;
            _ = EfiEvidence.RelativePath(kernelRoot, document.Path, "page_entry_dependency_outside_kernel");
            var admitted = RequirePageEntryJoin(efi, document);
            HostNoStdLibClosure.RequirePlanningTypes(host, document);
            HostNoStdLibClosure.RequirePlanningTypes(efi, admitted);
            selected.Add(admitted.Path);
        }
        if (selected.Count == 0)
            throw new InvalidOperationException("page_entry_dependency_empty");
        return efi.Documents.Where(document => selected.Contains(document.Path)).ToArray();
    }

    private static string NoStdLibPageEntryCompileItems(string root, string shim)
    {
        var sources = PageEntrySources(root, HostSourceCatalog.Project("src/OS.Kernel/OS.Kernel.csproj"),
            PageEntryEfi("SingleMinimalApi").Sources);
        // This fixture has the same original 17-type shim contract as the
        // allocator oracles; the shared validator does not add source inputs.
        HostBootPageAllocatorSources.ValidateShimClosure(sources, shim);
        foreach (var source in sources)
            AuthorityFiles.RequirePlainPath(root, source.Path, "page_entry_source_link");
        return string.Join("\n", sources.Select(source => "<Compile Include=\"" + EscapeXml(source.Path)
            + "\" Link=\"" + EscapeXml(Path.GetRelativePath(root, source.Path)) + "\" />"));
    }

    private static bool PageEntryProfileBoundary(string root, CSharpSourceCatalog kernel, CSharpSourceCatalog host, string workload)
    {
        var evaluation = PageEntryEfi(workload);
        var source = evaluation.Sources;
        using var parsed = JsonDocument.Parse(evaluation.EvaluationJson);
        var properties = parsed.RootElement.GetProperty("Properties");
        var items = parsed.RootElement.GetProperty("Items");
        if (properties.GetProperty("Configuration").GetString() != "Release"
            || properties.GetProperty("OSWorkloadProfile").GetString() != workload
            || items.GetProperty("Reference").GetArrayLength() != 0
            || items.GetProperty("ProjectReference").GetArrayLength() != 0 || source.Compilation.References.Any())
            return false;
        var compile = items.GetProperty("Compile").EnumerateArray().ToArray();
        if (compile.Length == 0 || compile.Any(item => string.IsNullOrEmpty(item.GetProperty("Identity").GetString())
            || !Path.IsPathFullyQualified(item.GetProperty("FullPath").GetString() ?? ""))
            || !compile.Select(item => Path.GetFullPath(item.GetProperty("FullPath").GetString()!))
                .SequenceEqual(source.Documents.Select(document => Path.GetFullPath(document.Path)), StringComparer.OrdinalIgnoreCase))
            return false;
        var hostPaths = HostSourceText.DocumentSources(host, typeof(X64PageTableEntryTests).FullName!)
            .Select(document => document.Path).ToHashSet(StringComparer.OrdinalIgnoreCase);
        if (source.Compilation.GetTypeByMetadataName(typeof(X64PageTableEntryTests).FullName!) is not null
            || source.Documents.Any(document => hostPaths.Contains(document.Path)))
            return false;
        _ = PageEntrySources(root, kernel, source);
        return source.Type("OS.Boot.EfiEntry").TypeKind == TypeKind.Class
            && source.Type("System.Object").SpecialType == SpecialType.System_Object;
    }

    private static bool PageEntryMarkerShape(CSharpSourceCatalog host)
    {
        string owner = HostSourceText.Documents(host, typeof(X64PageTableEntryTests).FullName!);
        var method = host.Method(typeof(X64PageTableEntryTests).FullName!, nameof(RunAll), symbol =>
            symbol.IsStatic && symbol.Arity == 0 && symbol.ReturnsVoid && symbol.Parameters.Length == 0
                && symbol.DeclaredAccessibility == Accessibility.Internal);
        _ = host.MethodInvocations(method);
        string sequence = method.ToString();
        int failureGate = sequence.IndexOf("if (failures != 0)", StringComparison.Ordinal);
        int aggregateFailure = sequence.IndexOf("Console.WriteLine(\"TEST_FAIL \" + IssueTestName", StringComparison.Ordinal);
        int aggregateThrow = sequence.IndexOf("\"M01-011 x64 page-table entry tests failed:", StringComparison.Ordinal);
        int readyWrite = sequence.IndexOf("Console.WriteLine(ReadyMarker)", StringComparison.Ordinal);
        int aggregatePass = sequence.IndexOf("Console.WriteLine(\"TEST_PASS \" + IssueTestName)", StringComparison.Ordinal);
        return CountOccurrences(owner, "\"" + ReadyMarker + "\"") == 1
            && CountOccurrences(owner, "Console.WriteLine(\"TEST_START \" + IssueTestName)") == 1
            && CountOccurrences(owner, "Console.WriteLine(\"TEST_FAIL \" + IssueTestName") == 1
            && CountOccurrences(owner, "Console.WriteLine(\"TEST_PASS \" + IssueTestName)") == 1
            && failureGate >= 0 && aggregateFailure > failureGate && aggregateThrow > aggregateFailure
            && readyWrite > aggregateThrow && aggregatePass > readyWrite
            && !owner.Contains("OS_" + "BOOT_OK", StringComparison.Ordinal)
            && !owner.Contains("OS_" + "SMOKE_PASS", StringComparison.Ordinal);
    }

    private static bool PageEntryMarkerBoundary(string root, CSharpSourceCatalog host)
    {
        if (!PageEntryMarkerShape(host))
            return false;
        var documents = HostSourceText.DocumentSources(host, typeof(X64PageTableEntryTests).FullName!);
        foreach (var document in documents)
            if (CSharpSourceDocument.Read(document.Path, (CSharpParseOptions)document.Syntax.Options).Sha256 != document.Sha256)
                return false;
        var owners = documents.Select(document => Path.GetFullPath(document.Path)).ToHashSet(StringComparer.OrdinalIgnoreCase);
        string[] scanRoots = ["src", "std", "apps", "tools", "tests", "scripts", Path.Combine(".gitea", "workflows")];
        foreach (string relativeRoot in scanRoots)
        {
            string scanRoot = Path.Combine(root, relativeRoot);
            if (!Directory.Exists(scanRoot))
                continue;
            foreach (string file in Directory.EnumerateFiles(scanRoot, "*", SearchOption.AllDirectories))
            {
                if (owners.Contains(Path.GetFullPath(file)) || HasDirectorySegment(file, "bin")
                    || HasDirectorySegment(file, "obj") || HasDirectorySegment(file, "artifacts") || !IsExecutableSource(file))
                    continue;
                if (File.ReadAllText(file).Contains(ReadyMarker, StringComparison.Ordinal))
                {
                    Console.WriteLine("M01_011_BOUNDARY_DIAGNOSTIC duplicate=" + Path.GetRelativePath(root, file));
                    return false;
                }
            }
        }
        return true;
    }
