using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using OS.Tooling;

/// <summary>Host-only source closure for the existing one-page allocation and exact-inverse free oracles. The caller retains its own ABI, raw-source, marker and runtime checks.</summary>
internal static class HostBootPageAllocatorSources
{
    private const string Owner = "OS.Kernel.Memory.BootPageAllocatorMutator";

    internal static CSharpSourceDocument[] Select(string root, CSharpSourceCatalog host, CSharpSourceCatalog efi)
    {
        string kernelRoot = Path.Combine(root, "src", "OS.Kernel");
        string objectRoot = Path.GetFullPath(Path.Combine(kernelRoot, "obj")) + Path.DirectorySeparatorChar;
        var selected = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var document in host.DependencySources(Owner))
        {
            var syntax = document.Syntax.GetRoot();
            var declarations = syntax.DescendantNodes().Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax).ToArray();
            bool generated = document.IsGenerated || document.Text.AsSpan(0, Math.Min(document.Text.Length, 256)).Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
            if (generated && document.Path.StartsWith(objectRoot, StringComparison.OrdinalIgnoreCase) && declarations.Length == 0 && syntax is CompilationUnitSyntax { Members.Count: 0, Externs.Count: 0 })
                continue;
            _ = EfiEvidence.RelativePath(kernelRoot, document.Path, "one_page_dependency_outside_kernel");
            var admitted = efi.Documents.SingleOrDefault(value => string.Equals(value.Path, document.Path, StringComparison.OrdinalIgnoreCase));
            if (admitted is null || admitted.Sha256 != document.Sha256)
                throw new InvalidOperationException("one_page_efi_source_join " + document.Path);
            var model = host.Compilation.GetSemanticModel(document.Syntax);
            if (declarations.Length == 0 || declarations.Any(node => model.GetDeclaredSymbol(node) is not INamedTypeSymbol type || type.ContainingNamespace.ToDisplayString() is not ("OS.Boot" or "OS.Kernel.Memory")))
                throw new InvalidOperationException("one_page_dependency_layer " + document.Path);
            var efiModel = efi.Compilation.GetSemanticModel(admitted.Syntax);
            if (admitted.Syntax.GetRoot().DescendantNodes().Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax).Any(node => efiModel.GetDeclaredSymbol(node) is not INamedTypeSymbol type || type.ContainingNamespace.ToDisplayString() is not ("OS.Boot" or "OS.Kernel.Memory")))
                throw new InvalidOperationException("one_page_efi_dependency_layer " + document.Path);
            selected.Add(admitted.Path);
        }

        if (selected.Count == 0)
            throw new InvalidOperationException("one_page_dependency_empty");
        return efi.Documents.Where(document => selected.Contains(document.Path)).ToArray();
    }

    internal static void ValidateShimClosure(IReadOnlyList<CSharpSourceDocument> sources, string shim)
    {
        var parse = new CSharpParseOptions(LanguageVersion.CSharp14, preprocessorSymbols: ["NOSTDLIB_EFI"]);
        var shimTree = CSharpSyntaxTree.ParseText(shim, parse, "NoStdLibShim.cs");
        string[] allowed = ["System.Object", "System.ValueType", "System.Enum", "System.Delegate", "System.MulticastDelegate", "System.Attribute", "System.Void", "System.Boolean", "System.Byte", "System.Int32", "System.UInt32", "System.UInt64", "System.IntPtr", "System.UIntPtr", "System.AttributeTargets", "System.AttributeUsageAttribute", "System.Runtime.CompilerServices.IsReadOnlyAttribute"];
        var declarations = shimTree.GetRoot().DescendantNodes().OfType<BaseTypeDeclarationSyntax>().ToArray();
        var identities = declarations.Select(type => string.Join(".", type.Ancestors().OfType<BaseNamespaceDeclarationSyntax>().Reverse().Select(space => string.Concat(space.Name.DescendantTokens().Select(token => token.ValueText)))) + "." + type.Identifier.ValueText).ToArray();
        if (!identities.Order(StringComparer.Ordinal).SequenceEqual(allowed.Order(StringComparer.Ordinal)) || declarations.Any(type => type.Ancestors().OfType<BaseTypeDeclarationSyntax>().Any() || type is TypeDeclarationSyntax { TypeParameterList: not null }) || shimTree.GetRoot().DescendantNodes().OfType<DelegateDeclarationSyntax>().Any())
            throw new InvalidOperationException("one_page_shim_surface");
        var compilation = CSharpCompilation.Create("OnePageShimClosure", sources.Select(document => CSharpSyntaxTree.ParseText(document.Text, parse, document.Path)).Append(shimTree), [], new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errors = compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidOperationException("one_page_shim_closure " + string.Join("; ", errors.Select(error => error.ToString())));
    }

    internal static bool LegacyLayersExcluded(CSharpSourceCatalog source)
    {
        string[] excluded = ["BootPageAllocatorStateStatus", "BootPageAllocatorStateInitResult", "BootPageAllocatorStateInitializer", "BootPageFreeListPlanStatus", "BootPageFreeListPlanResult", "BootPageFreeListBuilder", "BootPageAllocatorPlanStatus", "BootPageFreeSegment", "BootPageAllocatorPlanResult", "BootPageAllocatorPlanner", "BootMemoryRegionPlanStatus", "BootMemoryUsableRange", "BootMemoryReservedRange", "BootMemoryRegionPlanResult", "BootMemoryRegionPlanner"];
        return excluded.All(name => source.Compilation.GetTypeByMetadataName("OS.Kernel.Memory." + name) is null);
    }
}
